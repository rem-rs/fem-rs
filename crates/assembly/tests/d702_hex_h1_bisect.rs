fn u0(x: &[f64]) -> (f64, f64) {
    // exp(-i k z), k = sqrt(mu*omega*(eps*omega - i sigma))
    let k2r = MU * OMEGA * (EPS * OMEGA);
    let k2i = -MU * OMEGA * SIGMA;
    let r = (k2r * k2r + k2i * k2i).sqrt().sqrt();
    let t = 0.5 * k2i.atan2(k2r);
    let (kr, ki) = (r * t.cos(), r * t.sin());
    let z = x[x.len() - 1];
    let e = (ki * z).exp();
    (e * (-kr * z).cos(), e * (-kr * z).sin())
}

fn tag_key(t: f64) -> i64 { (t * 2.0).round() as i64 }

/// g2r[g] = rust global dof carrying MFEM global dof g (by location tag).
fn tag_g2r(space: &H1Space<fem_mesh::Mesh<3>>, cpp_tags: &[f64]) -> Vec<usize> {
    let dm = space.dof_manager();
    let mut rust: HashMap<i64, usize> = HashMap::new();
    for d in 0..space.n_dofs() {
        let c = dm.dof_coord(d as u32);
        let t = 10000.0 * c[0] + 100.0 * c[1] + c[2];
        assert!(rust.insert(tag_key(t), d).is_none(), "duplicate tag {t}");
    }
    cpp_tags.iter().map(|&t| rust[&tag_key(t)]).collect()
}

/// Dense complex solve of the flat [Kre -Kim; Kim Kre] system.
fn dense_solve(a: &[Vec<f64>], b: &[f64]) -> Vec<f64> {
    let n = b.len();
    let mut m = a.to_vec();
    let mut rhs = b.to_vec();
    for c in 0..n {
        let p = (c..n).fold(c, |best, r| {
            if m[r][c].abs() > m[best][c].abs() { r } else { best }
        });
        m.swap(c, p);
        rhs.swap(c, p);
        for r in 0..n {
            if r != c && m[r][c].abs() > 1e-300 {
                let f = m[r][c] / m[c][c];
                for k in c..n {
                    m[r][k] -= f * m[c][k];
                }
                rhs[r] -= f * rhs[c];
            }
        }
    }
    (0..n).map(|r| rhs[r] / m[r][r]).collect()
}

fn mesh_from_text(text: &str, name: &str) -> fem_mesh::Mesh<3> {
    let p = std::env::temp_dir().join(name);
    std::fs::write(&p, text).expect("write mesh fixture");
    let data = read_mfem_file(p.to_str().unwrap()).expect("read mesh");
    data.mesh3d.expect("3d mesh")
}

