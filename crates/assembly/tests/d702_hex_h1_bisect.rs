/// Two-hex Q2: the full example pipeline (assemble + nodal BC with BOTH re
/// and im + elimination + solve) must land on MFEM's solution at every dof,
/// and the L2 error must match ComputeL2Error.
#[test]
fn d702_two_hex_q2_full_pipeline() {
    let mesh = mesh_from_text(TWO_HEX_TEXT, "d702_two_hex.mesh");
    let space = H1Space::new(mesh.clone(), 2);
    assert_eq!(space.n_dofs(), 45);
    let g2r = tag_g2r(&space, &CPP_TWO_HEX_Q2_TAGS);

    let mut sys = ComplexAssembler::assemble(
        &space,
        &[&DiffusionIntegrator { kappa: 1.0 / MU }],
        &[&MassIntegrator { rho: EPS }],
        &[&MassIntegrator { rho: SIGMA }],
        OMEGA,
        5,
    );
    let all_tags: Vec<i32> = mesh.unique_boundary_tags();
    let ess_bdr: Vec<usize> = boundary_dofs(&mesh, space.dof_manager(), &all_tags)
        .into_iter()
        .map(|d| d as usize)
        .collect();
    assert_eq!(ess_bdr.len(), 42, "essential dof count");

    let u_proj_re = space
        .interpolate(&|x: &[f64]| u0(x).0)
        .as_slice()
        .to_vec();
    let u_proj_im = space
        .interpolate(&|x: &[f64]| u0(x).1)
        .as_slice()
        .to_vec();
    let bc_re: Vec<f64> = ess_bdr.iter().map(|&d| u_proj_re[d]).collect();
    let bc_im: Vec<f64> = ess_bdr.iter().map(|&d| u_proj_im[d]).collect();
    let mut rhs = vec![0.0f64; 90];
    sys.apply_dirichlet(&ess_bdr, &bc_re, &bc_im, &mut rhs);
    let flat = sys.to_flat_csr();
    let mut a_dense = vec![vec![0.0f64; 90]; 90];
    for i in 0..90 {
        for p in flat.row_ptr[i]..flat.row_ptr[i + 1] {
            a_dense[i][flat.col_idx[p] as usize] = flat.values[p];
        }
    }
    let x = dense_solve(&a_dense, &rhs);

    let (mut max_d, mut which) = (0.0f64, 0usize);
    for (dof, re_, im_) in CPP_TWO_HEX_Q2_SOL.iter() {
        let r = g2r[*dof];
        let d = ((x[r] - re_).abs()).max((x[45 + r] - im_).abs());
        if d > max_d {
            max_d = d;
            which = *dof;
        }
    }
    println!("two-hex-q2: max solution |rust-cpp| = {max_d:.3e} (dof {which})");
    assert!(max_d < 1e-9, "solution diverges ({max_d} at dof {which})");

    let gf = ComplexGridFunction {
        u_re: x[..45].to_vec(),
        u_im: x[45..].to_vec(),
    };
    let (er, ei) = gf.compute_l2_error(
        &|x: &[f64]| u0(x).0,
        &|x: &[f64]| u0(x).1,
        7,
        &space,
    );
    println!("two-hex-q2: L2 re={er:.14} im={ei:.14}  cpp {CPP_TWO_HEX_Q2_L2:?}");
    assert!((er - CPP_TWO_HEX_Q2_L2.0).abs() < 1e-9);
    assert!((ei - CPP_TWO_HEX_Q2_L2.1).abs() < 1e-9);
}

/// The D702 gauge on `data/inline-hex.mesh` (ex22 `-p 0 -o 1`, 4x4x4 hexes,
/// dense solve instead of GMRES — same solution to ~1e-12):
///   * example's CURRENT bc (`im` zeroed)  → C++ `-bc 1` gauge values,
///   * corrected bc (im from u0_exact)     → C++ ex22 (`-bc 0`) values.
/// Both directions reproduce C++ to ~1e-9, proving the deviation layer is
/// exactly the dropped imaginary BC in `solve_3d_p0` (example-side fix D718).
#[test]
fn d702_inline_hex_o1_bc_gauge() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../data/inline-hex.mesh");
    let data = read_mfem_file(path).expect("read inline-hex.mesh");
    let mesh = data.mesh3d.expect("3d mesh");
    let space = H1Space::new(mesh.clone(), 1);
    let n = space.n_dofs();
    assert_eq!(n, 125);
    let dm = space.dof_manager();
    let all_tags: Vec<i32> = mesh.unique_boundary_tags();
    let ess_bdr: Vec<usize> = boundary_dofs(&mesh, dm, &all_tags)
        .into_iter()
        .map(|d| d as usize)
        .collect();

    let run = |zero_im: bool| -> (f64, f64) {
        let mut sys = ComplexAssembler::assemble(
            &space,
            &[&DiffusionIntegrator { kappa: 1.0 / MU }],
            &[&MassIntegrator { rho: EPS }],
            &[&MassIntegrator { rho: SIGMA }],
            OMEGA,
            3,
        );
        let mut bc_re = vec![0.0f64; ess_bdr.len()];
        let mut bc_im = vec![0.0f64; ess_bdr.len()];
        for (slot, &d) in ess_bdr.iter().enumerate() {
            let c = dm.dof_coord(d as u32).to_vec();
            let (ur, ui) = u0(&c);
            bc_re[slot] = ur;
            if !zero_im {
                bc_im[slot] = ui;
            }
        }
        let mut rhs = vec![0.0f64; 2 * n];
        sys.apply_dirichlet(&ess_bdr, &bc_re, &bc_im, &mut rhs);
        let flat = sys.to_flat_csr();
        let n2 = 2 * n;
        let mut a_dense = vec![vec![0.0f64; n2]; n2];
        for i in 0..n2 {
            for p in flat.row_ptr[i]..flat.row_ptr[i + 1] {
                a_dense[i][flat.col_idx[p] as usize] = flat.values[p];
            }
        }
        let x = dense_solve(&a_dense, &rhs);
        let gf = ComplexGridFunction {
            u_re: x[..n].to_vec(),
            u_im: x[n..].to_vec(),
        };
        gf.compute_l2_error(
            &|x: &[f64]| u0(x).0,
            &|x: &[f64]| u0(x).1,
            5,
            &space,
        )
    };

    let wrong = run(true);
    println!("inline-hex o1 bc_im=0 (example current): {wrong:.14?}");
    println!("  cpp -bc 1 gauge:                       {CPP_INLINE_HEX_O1_BC1:?}");
    assert!((wrong.0 - CPP_INLINE_HEX_O1_BC1.0).abs() < 1e-9);
    assert!((wrong.1 - CPP_INLINE_HEX_O1_BC1.1).abs() < 1e-9);

    let fixed = run(false);
    println!("inline-hex o1 bc_im=exact (fix):         {fixed:.14?}");
    println!("  cpp ex22 (-bc 0):                      {CPP_INLINE_HEX_O1_BC0:?}");
    assert!((fixed.0 - CPP_INLINE_HEX_O1_BC0.0).abs() < 1e-9);
    assert!((fixed.1 - CPP_INLINE_HEX_O1_BC0.1).abs() < 1e-9);
}
