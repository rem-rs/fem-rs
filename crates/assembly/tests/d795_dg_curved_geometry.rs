//! D795-1 — DG assembly **element geometry convention** regression pin.
//!
//! # The debt
//!
//! fem-rs' `DgAssembler` used a corner-bilinear (affine/bilinear-from-corners)
//! element geometry — `simplex_jac` / `quad_jac_at_01` over the element's four
//! corners, `nor = h_chord/2 · unit_normal`, and element reference points
//! obtained by *inverting the physical map*.  MFEM's `DGDiffusionIntegrator` /
//! `DiffusionIntegrator` / `DGDirichletLFIntegrator` instead evaluate the
//! element's **isoparametric** transformation:
//!
//! * `Trans.Elem1->Weight()` = det J of the order-`g` curved map,
//! * `nor = CalcOrtho(Trans.Jacobian())`, where `Trans.Jacobian()` is the
//!   composed face Jacobian `J_elem(eip)·d(eip)/dξ` of the `[0,1]` reference
//!   segment (weights sum to 1 — `IntRules.Get(Geometry::SEGMENT, 2)` is two
//!   Gauss points at 0.2113…/0.7886…, `w = 0.5` each),
//! * the element reference point from the **reference** composition
//!   (`Trans.SetAllIntPoints` / `Loc1.Transform`) — never from a physical
//!   inverse map.
//!
//! On straight-sided elements the two conventions agree; on a curved element
//! they differ at O(h²) — the mode-`VOL` system below moves by 1.4 in relative
//! terms (all 256 entries change) — so this test uses a mesh with genuinely
//! curved elements.  The `MFEM_*` gold blocks are 17-digit dumps of MFEM
//! 4.10's own assembly over the *same* mesh: see `tmp/d795/d795_probe.cpp`
//! (dump `tmp/d795/red_cpp_dump.txt`, comparing harness `tmp/d795/cmp.py`).
//!
//! # Mesh
//!
//! 2×2 quadrilateral elements on `[0,1]²`, `SetCurvature(3, true)` (order-3
//! discontinuous geometry, `L2_T1_2D_P3`), then the smooth bend
//! `(X,Y) ↦ (X(1+0.15Y(1−Y)), Y+0.15XY(1−Y))` applied to every geometry node —
//! exactly the C++ probe's `MakeCartesian2D(2,2,QUADRILATERAL,1,1,1)` +
//! `SetCurvature(3,true)` + `Transform(curve_min)` flow.
//!
//! # Modes (matching the C++ `[SYSMAT] mode=k`)
//!
//! * `VOL`  = `DiffusionIntegrator` + interior `DGDiffusionIntegrator`
//!            (`assemble_dg(.., Some(&[]))`)
//! * `ALL`  = the same `+ DGDiffusionIntegrator` on **all** boundary faces
//! * `TAG3` = the same `+ DGDiffusionIntegrator` on boundary tag 3 only
//!
//! with `a = 1`, `sigma = −1`, `kappa = 4`, face quad order `2·order = 2`.
//!
//! MFEM: `DGDiffusionIntegrator::AssembleFaceMatrix` (bilininteg.cpp:3770),
//! `DiffusionIntegrator::AssembleElementMatrix` (:934),
//! `Mesh::GetFaceTransformation` (:539), `CalcOrtho`, `CalcAdjugate`.

