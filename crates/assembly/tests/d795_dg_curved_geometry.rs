/// Tolerance for every gold comparison: MFEM's dump is 17-digit, but the two
/// codes sum the same products in a different order, so the recoverable
/// agreement is at the 1e-13 level (measured max relative deviation 1.5e-13).
const RTOL: f64 = 1e-12;

fn rel(a: f64, b: f64) -> f64 {
    let d = (a - b).abs();
    let s = a.abs().max(b.abs());
    if s < 1e-12 { d } else { d / s }
}

fn parse_matrix(s: &str) -> Vec<Vec<f64>> {
    s.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| l.split_whitespace().map(|v| v.parse().unwrap()).collect())
        .collect()
}

/// 2×2 quad mesh on `[0,1]²`, order-3 discontinuous geometry, smooth bend.
