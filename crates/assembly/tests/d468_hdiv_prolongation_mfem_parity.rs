/// Round a coordinate to the 1e-9 join grid.
fn q(v: f64) -> i64 {
    (v * 1e9).round() as i64
}

/// Face identity key: the face's vertex coordinates, sorted lexicographically
/// and flattened to the 1e-9 grid.  (Face midpoints are NOT unique identifiers
/// across the two triangulations — a midline of one shares its midpoint with a
/// sub-face of the other.)
fn face_key(mut vs: Vec<[f64; 3]>) -> Vec<i64> {
    let mut s: Vec<[i64; 3]> = vs
        .drain(..)
        .map(|c| [q(c[0]), q(c[1]), q(c[2])])
        .collect();
    s.sort();
    s.into_iter().flatten().collect()
}

fn coord(mesh: &Mesh<2>, v: u32) -> [f64; 3] {
    let c = mesh.node_coords(v);
    [c[0], c[1], 0.0]
}

fn coord3(mesh: &Mesh<3>, v: u32) -> [f64; 3] {
    let c = mesh.node_coords(v);
    [c[0], c[1], c[2]]
}

/// fem-rs face table (2-D): face vertex key → global RT0 dof.
fn face_dofs_2d(space: &HDivSpace<Mesh<2>>, mesh: &Mesh<2>, quad: bool) -> HashMap<Vec<i64>, u32> {
    let mut out = HashMap::new();
    for e in 0..mesh.n_elements() as u32 {
        let nd = mesh.element_nodes(e);
        let edges: &[(usize, usize)] = if quad {
            &[(0, 1), (1, 2), (2, 3), (3, 0)]
        } else {
            &[(0, 1), (1, 2), (2, 0)]
        };
        for &(a, b) in edges {
            let (va, vb) = (nd[a], nd[b]);
            let dof = space
                .edge_face_dof(EdgeKey::new(va, vb))
                .unwrap_or_else(|| panic!("missing RT0 dof for edge {va}-{vb}"));
            out.insert(face_key(vec![coord(mesh, va), coord(mesh, vb)]), dof);
        }
    }
    out
}

