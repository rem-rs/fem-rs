//! D468/D469/D460 — RT0 H(div) prolongation against MFEM probe truth.
//!
//! MFEM semantics (`mfem410 fem/fe/fe_base.cpp:1600 LocalInterpolation_RT`,
//! assembled by `RefinementMatrix_main` with first-writer-wins rows and
//! signed-dof orientation signs): for every fine dof k with parent element p,
//!
//! ```text
//! P[k, j] = s_k · φ_j^p(F(x̂_k)) · (adjJ_Fᵀ n̂_k) · s_j
//! ```
//!
//! where F is the affine child embedding (fine-ref → parent-ref), (x̂_k, n̂_k)
//! the fine dof's reference node/normal, φ_j the parent's RT0 reference basis,
//! and s the face-orientation signs.  Rows are dense — midline faces mix all
//! parent dofs — and each fine dof is written once.  Because fem-rs's RT
//! reference bases are not all point-dual (TetRTk carries W = 2I, HexRTk a
//! non-uniform dual), the rows are mapped through the reference dual matrix:
//! `P = B · W⁻¹` with `W[i][j] = φ_j(x̂_i)·n̂_i`, which makes the operator
//! basis-convention agnostic.
//!
//! The truth tables below were dumped from MFEM 4.10 (`tmp/d468/probe.cpp`:
//! `Mesh::UniformRefinement` + `fes.Update()` + `SetUpdateOperatorType(
//! MFEM_SPARSEMAT)`, unit-vector column extraction).  They are joined to
//! fem-rs dofs by **face vertex coordinates** (sorted), not face midpoints —
//! the two triangulations are mirror images and midlines of one mesh share
//! midpoints with sub-faces of the other.

