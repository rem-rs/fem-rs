/// A constant field is exactly representable in RT0 on every mesh, so the
/// prolongation of its coarse projection must equal the fine projection
/// dof-for-dof.  The historical builder failed this: internal sub-faces took
/// the double-counted full flux (D469/D460) and midline rows were empty (D468).
#[test]
fn d468_rt0_constant_field_prolongs_exactly() {
    let c2 = [1.3_f64, -0.7];
    for (name, mesh) in [
        ("tri", mfem_tri_mesh()),
        ("quad 2x2", Mesh::<2>::unit_square_quad(2)),
    ] {
        let fine_mesh = refine_uniform(&mesh);
        let coarse_space = HDivSpace::new(mesh, 0);
        let fine_space = HDivSpace::new(fine_mesh, 0);
        let (p, _) = build_prolongation_hdiv(&coarse_space, &fine_space);
        let x_c = coarse_space.interpolate_vector(&|_| c2.to_vec());
        let x_f = fine_space.interpolate_vector(&|_| c2.to_vec());
        let mut y = vec![0.0_f64; fine_space.n_dofs()];
        p.spmv(x_c.as_slice(), &mut y);
        for i in 0..fine_space.n_dofs() {
            assert!(
                (y[i] - x_f.as_slice()[i]).abs() <= 1e-12,
                "{name}: constant-flux dof {i}: P·x_c = {} vs fine projection {}",
                y[i],
                x_f.as_slice()[i]
            );
        }
    }
    let c3 = [0.9_f64, 0.4, -1.1];
    // tet RT0 stays on the legacy path (D481) — covered by the ignored tet
    // parity oracle above until its octahedron midline rows are resolved.
    for (name, mesh) in [("hex", Mesh::<3>::unit_cube_hex(1))] {
        let fine_mesh = fem_mesh::refine_uniform_3d(&mesh);
        let coarse_space = HDivSpace::new(mesh, 0);
        let fine_space = HDivSpace::new(fine_mesh, 0);
        let (p, _) = build_prolongation_hdiv(&coarse_space, &fine_space);
        let x_c = coarse_space.interpolate_vector(&|_| c3.to_vec());
        let x_f = fine_space.interpolate_vector(&|_| c3.to_vec());
        let mut y = vec![0.0_f64; fine_space.n_dofs()];
        p.spmv(x_c.as_slice(), &mut y);
        for i in 0..fine_space.n_dofs() {
            assert!(
                (y[i] - x_f.as_slice()[i]).abs() <= 1e-12,
                "{name}: constant-flux dof {i}: P·x_c = {} vs fine projection {}",
                y[i],
                x_f.as_slice()[i]
            );
        }
    }
}
