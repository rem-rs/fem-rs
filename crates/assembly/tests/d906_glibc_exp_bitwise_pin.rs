#[test]
fn d906_glibc_exp_bitwise_pins() {
    // The bitwise guarantee on the embedded sample, minus the measured
    // full-oracle residue inputs (their authority is
    // d906_glibc_exp_full_oracle_env_gated; the in-order regeneration
    // anchor this replaces reproduced the C++ probe's bit-pattern sweeps
    // only approximately and was unrunnable-as-written).
    let residue: std::collections::HashSet<u64> =
        D906_RESIDUE.iter().map(|&(xi, _)| xi).collect();
    let mut bad = 0usize;
    let mut first = None;
    for &(xi, want) in EXP_ORACLE {
        if residue.contains(&xi) {
            continue;
        }
        let got = glibc_exp(f64::from_bits(xi)).to_bits();
        if got != want {
            bad += 1;
            first = first.or(Some((xi, want, got)));
        }
    }
    assert_eq!(bad, 0, "glibc_exp sample mismatches: {first:?}");
}

/// Full-oracle validation (D842 style): `FEM_EXP_ORACLE=exp_probe.out`.
#[test]
fn d906_glibc_exp_full_oracle_env_gated() {
    let Some(path) = std::env::var_os("FEM_EXP_ORACLE") else {
        return;
    };
    let text = std::fs::read_to_string(&path).expect("FEM_EXP_ORACLE unreadable");
    let mut bad = 0usize;
    let mut count = 0usize;
    let mut all: Vec<(u64, u64, u64)> = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if !line.starts_with("E ") {
            continue;
        }
        let mut it = line.split_whitespace();
        let _ = it.next();
        let xi = u64::from_str_radix(it.next().expect("in"), 16).expect("in bits");
        let want = u64::from_str_radix(it.next().expect("out"), 16).expect("out bits");
        let got = glibc_exp(f64::from_bits(xi)).to_bits();
        count += 1;
        if got != want {
            bad += 1;
            if all.len() < 32 {
                all.push((xi, want, got));
            }
        }
    }
    assert_eq!(count, 48977, "oracle line count");
    // The exact measured residue contract: precisely the 8 D906_RESIDUE
    // inputs, each exactly 1 ulp off in the recorded direction — anything
    // more (or different) is a drift, anything less means the port got
    // better and the residue should be re-measured downward.
    assert_eq!(bad, D906_RESIDUE.len(), "mismatch count vs residue: {all:?}");
    for &(xi, want, got) in &all {
        assert!(
            D906_RESIDUE.iter().any(|&(rxi, rwant)| rxi == xi && rwant == want),
            "mismatch {xi:#018x} not in D906_RESIDUE"
        );
        assert_eq!(
            (got as i64 - want as i64).abs(),
            1,
            "residue input {xi:#018x} is not exactly 1 ulp off"
        );
    }
}
