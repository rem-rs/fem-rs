/// The measured full-oracle residue (round-130): 8 of 48977 probe inputs,
/// all in the narrow `x ≈ 471.8` band (exp ≈ 2^816), all exactly 1 ulp with
/// mixed direction — the GCC-FMA polynomial contraction grouping of glibc
