fn mfem_entries(s: &str) -> Vec<(usize, usize, f64)> {
    s.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| {
            let t: Vec<&str> = l.split_whitespace().collect();
            (
                t[0].parse().expect("row"),
                t[1].parse().expect("col"),
                t[2].parse().expect("value"),
            )
        })
        .collect()
}

/// The acceptance gate: fem-rs' hex `curl_3d(ND2 → RT1)` entry-for-entry
/// against the MFEM 4.10 probe matrix on the same single-hex mesh
/// (the FIXTURE_MATCHES_PROBE check of the round-60 evidence).
#[test]
fn hex_nd2_rt1_matches_mfem_fixture() {
    let mesh = Mesh::<3>::unit_cube_hex(1);
    let nd = HCurlSpace::new(mesh.clone(), 2);
    let rt = HDivSpace::new(mesh.clone(), 1);
    assert_eq!(nd.n_dofs(), 54, "ND2 hex DOF count (MFEM 54)");
    assert_eq!(rt.n_dofs(), 36, "RT1 hex DOF count (MFEM 36)");

    let c = DiscreteLinearOperator::curl_3d(&nd, &rt)
        .expect("hex curl_3d(ND2→RT1) must assemble (D120)");
    assert_eq!(c.nrows, 36);
    assert_eq!(c.ncols, 54);

    let entries = mfem_entries(MFEM_SINGLE_HEX);
    assert_eq!(entries.len(), 216, "probe nnz");
    let mut max_dev = 0.0_f64;
    for (i, j, v) in &entries {
        let got = c.get(*i, *j);
        max_dev = max_dev.max((got - v).abs());
    }
    assert!(
        max_dev < 1e-10,
        "fem-rs curl_3d vs MFEM CurlInterpolator probe: max entry deviation {max_dev:.3e}"
    );
}
