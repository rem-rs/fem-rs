/// `IntRules.Get(SQUARE, 2*2+3)`: 4x4 Gauss-Legendre on [0,1]^2, x fastest.
#[test]
fn d842_quad_rule_order7_is_mfem_bitwise() {
    let fx = fixture();
    let (pts, wts) = fx.kernels.quadrature();
    assert_eq!(pts.len(), 16);
    let oracle = parse_vals(ORACLE_IR); // (x, w) pairs flattened
    for (q, ip) in pts.iter().enumerate() {
        assert_eq!(ip[0].to_bits(), oracle[2 * q].to_bits(), "ir[{q}].x");
        assert_eq!(wts[q].to_bits(), oracle[2 * q + 1].to_bits(), "ir[{q}].w");
    }
    assert_eq!(fx.kernels.integration_order(), 7);
}

/// `HyperelasticNLFIntegrator::AssembleElementGrad` — the 18x18 element
