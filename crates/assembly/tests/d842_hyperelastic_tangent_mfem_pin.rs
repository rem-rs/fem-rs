/// The slot order fed to the kernels must be MFEM's quad H1 dof_map order —
/// the perturbation is indexed by the MFEM local dof id, so a permuted slot
/// order would silently compare against the wrong position field.
#[test]
fn d842_slot_order_is_mfem_dof_map() {
    let fx = fixture();
    let want: [[f64; 2]; 9] = [
        [0.0, 0.0], [1.0, 0.0], [1.0, 1.0], [0.0, 1.0],
        [0.5, 0.0], [1.0, 0.5], [0.5, 1.0], [0.0, 0.5],
        [0.5, 0.5],
    ];
    for (k, rc) in fx.ref_xy.iter().enumerate() {
        assert_eq!(rc[0].to_bits(), want[k][0].to_bits(), "ref_xy[{k}].x");
        assert_eq!(rc[1].to_bits(), want[k][1].to_bits(), "ref_xy[{k}].y");
    }
}
