/// MFEM `InitialDeformation`-style integer-hash perturbation (probe `Pert`):
/// deterministic, integer arithmetic only — bit-identical on both sides.
fn pert(k: usize, comp: usize) -> f64 {
    let (m, modulo, half): (i64, i64, f64) = match comp {
        0 => (37, 23, 11.0),
        _ => (19, 17, 8.0),
    };
    ((k as i64 * m) % modulo) as f64 * 0.01 - half * 0.01
}

fn parse_vals(s: &str) -> Vec<f64> {
    s.split_whitespace().map(|t| t.parse::<f64>().unwrap()).collect()
}

fn assert_bitwise(name: &str, got: &[f64], want: &[f64]) {
    assert_eq!(got.len(), want.len(), "{name}: length {} != {}", got.len(), want.len());
    for (i, (g, w)) in got.iter().zip(want.iter()).enumerate() {
        assert_eq!(
            g.to_bits(), w.to_bits(),
            "{name}: entry {i} differs: got {g:e} (bits {:x}) want {w:e} (bits {:x})",
            g.to_bits(), w.to_bits()
        );
    }
}

/// One straight quad (unit square, MFEM CCW vertex order), P2 field, the
/// probe's position field and the geometry corners.
struct Fixture {
    corners: Vec<[f64; 2]>,
    ref_xy: Vec<[f64; 2]>,
    pos: Vec<f64>,
    kernels: MfemHyperelasticQuad,
}

fn fixture() -> Fixture {
    let mesh = Mesh::<2>::unit_square_quad(1);
    let re = h1_field_element(ElementType::Quad4, 2, PyramidBasisType::default());
    let ref_xy: Vec<[f64; 2]> = re.dof_coords().iter().map(|c| [c[0], c[1]]).collect();
    // The slot order must be MFEM's quad H1 dof_map order (vertices CCW,
    // bottom/right/top/left edges, interior): positions = reference coords
    // (identity map) + the perturbation indexed by the MFEM local dof id.
    let mut pos = vec![0.0_f64; 18];
    for k in 0..9usize {
        pos[k * 2] = ref_xy[k][0] + pert(k, 0);
        pos[k * 2 + 1] = ref_xy[k][1] + pert(k, 1);
    }
    let corners: Vec<[f64; 2]> = [(0.0, 0.0), (1.0, 0.0), (1.0, 1.0), (0.0, 1.0)]
        .iter().map(|&(x, y)| [x, y]).collect();
    let kernels = MfemHyperelasticQuad::new(&mesh, 2, 0.25, 5.0);
    Fixture { corners, ref_xy, pos, kernels }
}


/// MFEM dumps the element matrix/vector in its component-blocked slot order
/// (index = slot + comp*dof); this port uses the interleaved layout of
/// `VectorH1Space::element_dofs` (index = slot*dim + comp).  Remap bitwise.
fn blocked_vec_to_interleaved(v: &[f64], dof: usize) -> Vec<f64> {
    let mut out = vec![0.0_f64; 2 * dof];
    for s in 0..dof {
        for c in 0..2 {
            out[s * 2 + c] = v[s + c * dof];
        }
    }
    out
}

fn blocked_mat_to_interleaved(v: &[f64], dof: usize) -> Vec<f64> {
    let n = 2 * dof;
    let mut out = vec![0.0_f64; n * n];
    for s in 0..dof {
        for c in 0..2 {
            for t in 0..dof {
                for d in 0..2 {
                    out[(s * 2 + c) * n + (t * 2 + d)] =
                        v[(s + c * dof) * n + (t + d * dof)];
                }
            }
        }
    }
    out
}

