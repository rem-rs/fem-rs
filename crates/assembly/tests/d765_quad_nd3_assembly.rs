/// Element 0 of `data/inline-quad.mesh` at ND3: the ex22 real-operator element
/// matrix must equal MFEM's `AssembleElementMatrix` output.
#[test]
fn quad3_element_matrix_matches_mfem_elmat_dump() {
    let space = HCurlSpace::new(inline_quad(), 3);
    let dofs = space.element_dofs(0);
    let n = dofs.len();
    assert_eq!(n, 24, "ND3 quad element DOF count");
    assert_eq!(n * n, MFEM_ELMAT_QUAD0_P3.len());

    // The quadrature rule is part of the pin (D738: an ORDER, not a count):
    // `quad_order = 2p + 3 = 9` -> `quad_rule_01(9)` = 5x5 = 25 points, the
    // same rule the C++ probe passed to `IntRules.Get(SQUARE, 9)`.
    let paired = paired_vector_reference_element(SpaceType::HCurl, ElementType::Quad4, 2, 3);
    assert_eq!(paired.n_dofs(), n, "paired element vs space slot count");
    let rule = paired.quadrature(9);
    assert_eq!(rule.points.len(), 25, "quad_rule_01(9) must be the 5x5 rule");
    assert_eq!(rule.weights.len(), 25);

    let curl_curl = CurlCurlIntegrator { mu: 1.0 };
    let vec_mass = VectorMassIntegrator { alpha: -100.0 };
    let mut coo = CooMatrix::new(space.n_dofs(), space.n_dofs());
    accumulate_vector_bilinear_element(&space, 0, &[&curl_curl, &vec_mass], 9, &mut coo);
    let a = coo.into_csr_sorted();

    // `accumulate_vector_bilinear_element` folds the space's DOF-orientation
    // signs into the trial/test functions (`s_i s_j K_local`), while the MFEM
    // dump is the *raw* `AssembleElementMatrix` output (MFEM applies the same
    // signs later, when scattering through the signed `GetElementVDofs`).
    // Undo them here (s^2 = 1) so the pin compares the element bases; the
    // signs themselves are pinned slot-for-slot by
    // `crates/space/tests/d765_quad_nd3_pairing.rs`.
    let signs = space.element_signs(0);
    let mut max_rel = 0.0_f64;
    for i in 0..n {
        for j in 0..n {
            let got = a.get(dofs[i] as usize, dofs[j] as usize) * signs[i] * signs[j];
            let want = MFEM_ELMAT_QUAD0_P3[i * n + j];
            let scale = 1.0 + want.abs();
            assert!(
                (got - want).abs() <= 1e-12 * scale,
                "K({i},{j}) = {got:.17e} != MFEM {want:.17e} (rel {:.3e})",
                (got - want).abs() / scale
            );
            max_rel = max_rel.max((got - want).abs() / scale);
        }
    }
    assert!(max_rel < 1e-12, "max relative element-matrix deviation {max_rel:e}");
}

/// No row of the assembled global quad-ND3 system may be empty: the D765
/// failure mode was a *pairing* error (wrong basis for the space's tables), and
/// the classic silent variant of that is an unassembled DOF block (`D353`).
#[test]
fn quad3_global_system_has_no_silent_zero_rows() {
    use fem_assembly::VectorAssembler;
    let space = HCurlSpace::new(inline_quad(), 3);
    let n = space.n_dofs();
    assert_eq!(n, 312, "inline-quad ND3 DOF count");
    let curl_curl = CurlCurlIntegrator { mu: 1.0 };
    let vec_mass = VectorMassIntegrator { alpha: -100.0 };
    let a = VectorAssembler::assemble_bilinear(&space, &[&curl_curl, &vec_mass], 9);
    let mut worst = f64::INFINITY;
    for i in 0..n {
        let mut s = 0.0_f64;
        for j in 0..n {
            s += a.get(i, j).abs();
        }
        worst = worst.min(s);
    }
    assert!(
        worst > 1e-6,
        "assembled quad ND3 system has a (near) empty row: min row |sum| = {worst:e}"
    );
}
