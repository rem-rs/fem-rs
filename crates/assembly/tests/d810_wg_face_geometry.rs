//! D810-1 — the **wg family's face geometry** (`wg_poisson`, `wg_stokes`,
//! `wg_maxwell`) on curved simplex meshes.
//!
//! # The debt
//!
//! Each of the three modules carried its own private **chord route** for the
//! face stabilizer `α·∫_F φᵢφⱼ dS`: `face_geom_2d`/`face_geom_3d` built the
//! measure from the face's **corner nodes**, the quadrature point was the
//! linear interpolation of those corners, and the element reference point came
//! from *inverting* the element's vertex Jacobian (`local_phys_to_ref`).  That
//! is the route round 75 deleted from `dg.rs`/`dg_advection`/`dg_elasticity`/
//! `dg_hyperbolic` and round 76 from the PA kernels: exact only while the mesh
//! is straight, silently `O(h)`-wrong on a mesh carrying an order-`g` geometry
//! table.  Registration also undercounted the damage as "one line": the chord
//! route covered **three** things — the face measure, the face physical point,
//! and the reference-point inversion.
//!
//! The family now takes the whole face path from `dg_base::face_point_geom` /
//! `face_point_geom_3d` (the single arithmetic source round 75 introduced),
//! plus MFEM's face rules (`seg_rule` in 2-D, `tri_rule` in 3-D — the pre-fix
//! 2-D loop fed a *triangle* rule to a segment parameterisation and used only
//! its `ξ₀`).
//!
//! # The oracle (and what it proves)
//!
//! MFEM 4.10 has **no WG miniapp** (`miniapps/` has none), so there is no WG
//! truth to port.  What *is* available is the truth for the arithmetic the
//! family uses: `tmp/d78c/d810_probe.cpp` dumps MFEM's own
//! `FaceElementTransformations` on the **same curved fixtures** —
//! `MakeCartesian{2,3}D(1,1[,1], TRIANGLE/TETRAHEDRON)` + `SetCurvature(2)` +
//! the D787/D793 word-warp applied to every geometry dof and vertex — at the
//! face reference points of the wg rules themselves:
//!
//! * every face (boundary **and** interior), both sides,
//! * `nor = CalcOrtho(Trans.Jacobian())` (magnitude = face measure),
//! * `eip = GetElement{1,2}IntPoint()` (the `Loc1`/`Loc2` composition — the
//!   quantity the inversion used to approximate),
//! * `x = Elem->Transform(eip)` (the physical face point),
//! * `W = Elem->Weight()` (the element Jacobian determinant there).
//!
//! [`d810_1_face_primitive_matches_mfem`] compares them entry by entry with
//! fem-rs' `face_point_geom`/`face_point_geom_3d` — the *functions the wg
//! modules now call* — so it proves the wg face path's arithmetic equals
//! MFEM's on curved simplices.  It does **not** prove WG *methods* numbers
//! (no MFEM WG exists); the wg assembly-level pins below ([`wg_face_diff`]
//! against an independent assembly through the same primitive, and the
//! straight-mesh relation to the verbatim pre-fix route) are what bind the
//! modules to that primitive.
//!
//! The gold files are the probe's stdout verbatim (17 significant digits):
//! `crates/assembly/tests/data/d810_mfem_face_{tet,tri}_n1.txt`, regenerated by
//! `wsl -e bash -lc 'cd /home/quan/work/d78c && ./d810_probe tet 1 2'`.

