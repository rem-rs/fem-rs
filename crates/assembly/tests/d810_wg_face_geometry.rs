/// The pre-fix chord route does **not** reproduce MFEM on the curved fixture —
/// the teeth of the oracle above (the same faces, the same points, the
/// geometry route it replaced) — and, as the measurement also shows, its
/// reference-point **inversion** is inert on simplex faces.
#[test]
fn d810_1_chord_route_is_far_from_mfem_on_curved_cells() {
    let tet = curved_tet_mesh();
    let gold = parse_gold(GOLD_TET);
    let (mut worst_eip, mut worst_x, mut worst_nor) = (0.0_f64, 0.0_f64, 0.0_f64);
    for qp in &gold.qps {
        let elem = match_elem(&tet, &gold.elems[qp.e as usize]);
        let fv = &gold.faces[qp.f].fv;
        let (xp, nor_mag) = chord_point_normal(&tet, elem, fv, &gold.rps[qp.r]);
        let eip = chord_invert(&tet, elem, &xp);
        let gold_nor = qp.nor.iter().map(|v| v * v).sum::<f64>().sqrt();
        worst_nor = worst_nor.max((nor_mag - gold_nor).abs() / gold_nor.max(1e-30));
        for d in 0..3 {
            worst_eip = worst_eip.max((eip[d] - qp.eip[d]).abs());
            worst_x = worst_x.max((xp[d] - qp.x[d]).abs());
        }
    }
    println!(
        "pre-fix chord route vs MFEM (curved tet): max|Δeip|={worst_eip:.3e} \
         max|Δx|={worst_x:.3e} max rel|Δnor|={worst_nor:.3e}"
    );
    assert!(worst_x > 1e-3, "physical-point witness has no teeth: {worst_x:.3e}");
    assert!(worst_nor > 1e-2, "normal witness has no teeth: {worst_nor:.3e}");
    // Registration correction (round 78): the **reference-point inversion** —
    // the third leg D810-1's registration names — is provably inert on a
    // *simplex* face.  The pre-fix `local_phys_to_ref` inverts the element's
    // affine vertex map at the corner-interpolated physical point, and for an
    // affine `X` with `xp = Σ λᵢ X(vᵢ) = X(Σ λᵢ ξ(vᵢ))` that recovers
    // `Σ λᵢ ξ(vᵢ)` exactly — which is precisely MFEM's `Loc1` composition
    // (`face_point_geom`'s `eip`), a purely combinatorial affine map that never
    // sees the curvature.  So on curved simplex faces the inversion is *not* a
    // source of error here; what the chord route gets wrong is the face measure
    // and the face physical point.  (For the D799-3 quad case it *would* be:
    // a bilinear map's inverse is not affine.)
    assert!(
        worst_eip < 1e-13,
        "the inversion leg was measured inert ({worst_eip:.3e}), which the registration \
         calls a defect — re-derive the registration if this fires"
    );
}


/// The wg **Poisson** stabilizer on a curved mesh is exactly the independent
/// assembly through `face_point_geom` — and the chord route it replaced is
/// `O(1e-1)` off.  Also pins the straight-mesh relation to the pre-fix route.
fn wg_poisson_pins<const D: usize>(curved: &Mesh<D>, straight: &Mesh<D>, name: &str) {
    let qo = 3;
    let sp_c = L2Space::new(curved.clone(), 1);
    let sp_s = L2Space::new(straight.clone(), 1);

    // Curved: the wg face block IS the isoparametric one; the chord route is not.
    let wg_c = wg_face_diff(curved, &sp_c, qo);
    let iso_c = wg_face_block(curved, &sp_c, qo, 1.0, Route::Isoparametric);
    let chord_c = wg_face_block(curved, &sp_c, qo, 1.0, Route::Chord);
    let rel_iso = max_rel_diff(&wg_c, &iso_c);
    let rel_chord = max_rel_diff(&wg_c, &chord_c);
    println!(
        "{name} curved: wg face block vs isoparametric={rel_iso:.3e}, \
         vs pre-fix chord route={rel_chord:.3e}"
    );
    assert!(rel_iso < 1e-12, "{name}: wg face block != isoparametric ({rel_iso:.3e})");
    assert!(rel_chord > 1e-2, "{name}: the chord witness has no teeth ({rel_chord:.3e})");

    // Straight: the pre-fix route is reproduced by `Chord` (same measure, same
    // point — the only difference left is the rule).
    let wg_s = wg_face_diff(straight, &sp_s, qo);
    let iso_s = wg_face_block(straight, &sp_s, qo, 1.0, Route::Isoparametric);
    let chord_s = wg_face_block(straight, &sp_s, qo, 1.0, Route::Chord);
    let rel_iso_s = max_rel_diff(&wg_s, &iso_s);
    let rel_chord_s = max_rel_diff(&wg_s, &chord_s);
    println!(
        "{name} straight: wg face block vs isoparametric={rel_iso_s:.3e}, \
         vs chord route={rel_chord_s:.3e}"
    );
    assert!(rel_iso_s < 1e-12, "{name} straight: wg face block != isoparametric");
    if name == "tet" {
        // 3-D: the chord/corner-triangle measure is exactly half the reference
        // measure (`tri_rule` sums to 1/2, `|nor|` is twice the triangle area),
        // and the straight elements' composition and corner points coincide —
        // so the new block is exactly twice the pre-fix one.
        let doubled: Vec<Vec<f64>> =
            chord_s.iter().map(|r| r.iter().map(|v| 2.0 * v).collect()).collect();
        let rel = max_rel_diff(&wg_s, &doubled);
        println!("{name} straight: ||wg − 2·chord|| = {rel:.3e}");
        assert!(rel < 1e-12, "{name} straight: the measure normalization is not exactly 2x ({rel:.3e})");
    } else {
        // 2-D: the chord length IS the face measure exactly (so `h` and the
        // point did not move), the change is the rule — `seg_rule` (Σw = 1,
        // MFEM's face rule) instead of a triangle rule read along one axis
        // (Σw = 1/2, and its `ξ₀` values are not a 1-D quadrature at all), so
        // the pre-fix block is off by more than the measure factor alone.
        let doubled: Vec<Vec<f64>> =
            chord_s.iter().map(|r| r.iter().map(|v| 2.0 * v).collect()).collect();
        let beyond = max_rel_diff(&wg_s, &doubled);
        println!("{name} straight: ||wg − 2·chord|| = {beyond:.3e} (rule error, not just the factor)");
        assert!(
            rel_chord_s > 1e-2,
            "2-D straight: the pre-fix rule witness has no teeth ({rel_chord_s:.3e})"
        );
        assert!(
            beyond > 1e-2,
            "2-D straight: the pre-fix rule error beyond the measure factor is only {beyond:.3e}"
        );
    }
}

#[test]
fn d810_1_wg_poisson_face_block_is_the_isoparametric_one_2d() {
    wg_poisson_pins(&curved_tri_mesh(), &straight_tri_mesh(), "tri");
}

