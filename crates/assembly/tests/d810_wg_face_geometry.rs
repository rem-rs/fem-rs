#[derive(Debug, Clone)]
struct GoldFace {
    e1: i64,
    e2: i64,
    /// The face's vertices in MFEM's own order — the `(a, b[, c])` the Rust
    /// side must pass so that the reference parameterisation coincides.
    fv: Vec<u32>,
}

#[derive(Debug, Clone)]
struct GoldQp {
    f: usize,
    side: usize,
    e: i64,
    r: usize,
    nor: Vec<f64>,
    eip: Vec<f64>,
    x: Vec<f64>,
    w: f64,
}

#[derive(Debug)]
struct Gold {
    dim: usize,
    verts: Vec<Vec<f64>>,
    elems: Vec<Vec<u32>>,
    evols: Vec<f64>,
    rps: Vec<Vec<f64>>,
    faces: Vec<GoldFace>,
    qps: Vec<GoldQp>,
}

fn nums(s: &str) -> Vec<f64> {
    s.split(|c: char| !(c.is_ascii_digit() || c == '.' || c == '-' || c == 'e' || c == 'E' || c == '+'))
        .filter(|t| !t.is_empty() && *t != "-" && *t != "+")
        .map(|t| t.parse::<f64>().unwrap_or_else(|_| panic!("bad number {t:?} in {s:?}")))
        .collect()
}

/// `k=(...)` → the numbers inside the parentheses.
fn paren(line: &str, key: &str) -> Vec<f64> {
    let i = line.find(key).unwrap_or_else(|| panic!("no {key} in {line:?}"));
    let rest = &line[i + key.len()..];
    let j = rest.find(')').expect("unterminated tuple");
    nums(&rest[..j])
}

/// `k=<n>` → the number.
fn scalar(line: &str, key: &str) -> f64 {
    let i = line.find(key).unwrap_or_else(|| panic!("no {key} in {line:?}"));
    let rest = &line[i + key.len()..];
    let end = rest.find(|c: char| c == ' ' || c == ')' || c == '(').unwrap_or(rest.len());
    rest[..end].parse::<f64>().unwrap_or_else(|_| panic!("bad scalar in {line:?}"))
}

fn parse_gold(s: &str) -> Gold {
    let mut g = Gold {
        dim: 0,
        verts: Vec::new(),
        elems: Vec::new(),
        evols: Vec::new(),
        rps: Vec::new(),
        faces: Vec::new(),
        qps: Vec::new(),
    };
    for line in s.lines() {
        if let Some(r) = line.strip_prefix("[MESH] ") {
            g.dim = scalar(r, "dim=") as usize;
        } else if let Some(r) = line.strip_prefix("[V] ") {
            let v = nums(r);
            g.verts.push(v[1..].to_vec());
        } else if let Some(r) = line.strip_prefix("[ELEM] ") {
            let n = r.find(':').expect("ELEM has no ':'");
            let vs: Vec<u32> = nums(&r[n + 1..]).iter().map(|v| *v as u32).collect();
            g.elems.push(vs);
        } else if let Some(r) = line.strip_prefix("[EVOL] ") {
            g.evols.push(nums(r)[1]);
        } else if let Some(r) = line.strip_prefix("[RP] ") {
            g.rps.push(nums(r)[1..].to_vec());
        } else if let Some(r) = line.strip_prefix("[FACE] ") {
            let n = r.find(':').expect("FACE has no ':'");
            let head = nums(&r[..n]);
            g.faces.push(GoldFace {
                e1: head[1] as i64,
                e2: head[2] as i64,
                fv: nums(&r[n + 1..]).iter().map(|v| *v as u32).collect(),
            });
        } else if let Some(r) = line.strip_prefix("[FQP] ") {
            g.qps.push(GoldQp {
                f: scalar(r, "f=") as usize,
                side: scalar(r, "side=") as usize,
                // NB: `" e="` — a bare `"e="` also matches inside `"side="`.
                e: scalar(r, " e=") as i64,
                r: scalar(r, "r=") as usize,
                nor: paren(r, "nor="),
                eip: paren(r, "eip="),
                x: paren(r, "x="),
                w: scalar(r, "W="),
            });
        }
    }
    assert!(!g.qps.is_empty() && !g.faces.is_empty(), "empty gold");
    g
}

/// The `fem-rs` element with the **ordered** vertex tuple `tuple`.
fn match_elem<const D: usize>(mesh: &Mesh<D>, tuple: &[u32]) -> u32 {
    for e in 0..mesh.n_elems() as u32 {
        if mesh.element_nodes(e) == tuple {
            return e;
        }
    }
    panic!("no element with the ordered vertex tuple {tuple:?} — the fixtures diverged");
}

/// `∫_T |det J|` over the mesh's own geometry map (the `[EVOL]` quantity).
fn element_measure<const D: usize>(mesh: &Mesh<D>, e: u32) -> f64 {
    let dim = mesh.dim() as usize;
    let qf = if dim == 2 { tri_rule(10) } else { fem_element::quadrature::tet_rule(10) };
    let mut v = 0.0;
    for (qi, xi) in qf.points.iter().enumerate() {
        let arr: [f64; D] = std::array::from_fn(|k| xi[k]);
        let (j, _x) = fem_mesh::transformation::element_jacobian_at(mesh, e, &arr, dim);
        v += qf.weights[qi] * j.determinant().abs();
    }
    v
}

fn check_mesh_identity<const D: usize>(mesh: &Mesh<D>, gold: &Gold, name: &str) {
    assert_eq!(mesh.dim() as usize, gold.dim, "{name}: dimension");
    assert_eq!(mesh.n_nodes(), gold.verts.len(), "{name}: vertex count");
    let mut worst_v = 0.0_f64;
    for (i, gv) in gold.verts.iter().enumerate() {
        for d in 0..gold.dim {
            worst_v = worst_v.max((mesh.coords[i * gold.dim + d] - gv[d]).abs());
        }
    }
    assert!(worst_v < 1e-15, "{name}: vertices differ by {worst_v:.3e}");

    let mut worst_vol = 0.0_f64;
    for (i, ge) in gold.elems.iter().enumerate() {
        let e = match_elem::<D>(mesh, ge);
        let want = gold.evols[i];
        worst_vol = worst_vol.max((element_measure(mesh, e) - want).abs() / want.abs());
    }
    println!("{name}: mesh identity max|Δvertex|={worst_v:.3e} max rel|Δvol|={worst_vol:.3e}");
    assert!(worst_vol < 1e-13, "{name}: element measures differ by {worst_vol:.3e}");
}

/// The four quantities MFEM's `FaceElementTransformations` hands a DG/WG face
/// term, as `face_point_geom`(`_3d`) returns them.
struct RsFace {
    eip: Vec<f64>,
    x: Vec<f64>,
    nor: Vec<f64>,
    det_j: f64,
}

fn rs_face<const D: usize>(
    mesh: &Mesh<D>,
    elem: u32,
    fv: &[u32],
    xi: &[f64],
) -> RsFace {
    if D == 2 {
        let g = face_point_geom(mesh, elem, fv[0], fv[1], xi[0]);
        RsFace { eip: g.eip.to_vec(), x: g.xp.to_vec(), nor: g.nor.to_vec(), det_j: g.det_j }
    } else {
        let g = face_point_geom_3d(mesh, elem, fv[0], fv[1], fv[2], [xi[0], xi[1]]);
        RsFace { eip: g.eip.to_vec(), x: g.xp.to_vec(), nor: g.nor.to_vec(), det_j: g.det_j }
    }
}

/// MFEM's `FaceElementTransformations` vs `face_point_geom`(`_3d`) at every
/// face reference point of the wg rules, on every face, on both sides.
fn check_face_primitive<const D: usize>(
    mesh: &Mesh<D>,
    gold: &Gold,
    name: &str,
) -> (f64, f64, f64, f64, f64) {
    let (mut worst_nor, mut worst_eip, mut worst_x, mut worst_w) = (0.0_f64, 0.0_f64, 0.0_f64, 0.0_f64);
    let mut worst_dir = 0.0_f64;
    for qp in &gold.qps {
        let elem = match_elem::<D>(mesh, &gold.elems[qp.e as usize]);
        let fv = &gold.faces[qp.f].fv;
        let rs = rs_face(mesh, elem, fv, &gold.rps[qp.r]);
        // MFEM's `nor` is always Elem1's (outward from Elem1); Elem2's own
        // outward normal is its negative.  The comparison is
        // magnitude-relative: a bare per-component ratio blows up whenever one
        // component of the normal happens to be near zero (faces nearly
        // parallel to a coordinate plane), which is not a geometry error.
        let s = if qp.side == 1 { 1.0 } else { -1.0 };
        let gmag = qp.nor.iter().map(|v| v * v).sum::<f64>().sqrt();
        let rmag = rs.nor.iter().map(|v| v * v).sum::<f64>().sqrt();
        worst_nor = worst_nor.max((rmag - gmag).abs() / gmag.max(1e-300));
        for d in 0..gold.dim {
            worst_dir = worst_dir.max((s * rs.nor[d] - qp.nor[d]).abs() / gmag.max(1e-300));
            worst_eip = worst_eip.max((rs.eip[d] - qp.eip[d]).abs());
            worst_x = worst_x.max((rs.x[d] - qp.x[d]).abs());
        }
        worst_w = worst_w.max((rs.det_j - qp.w).abs() / qp.w.abs().max(1e-300));
    }
    println!(
        "{name}: max rel|Δ|nor||={worst_nor:.3e}  max|Δnor|/|nor|={worst_dir:.3e}           max|Δeip|={worst_eip:.3e}  max|Δx|={worst_x:.3e}  max rel|ΔW|={worst_w:.3e}"
    );
    (worst_nor.max(worst_dir), worst_eip, worst_x, worst_w, worst_dir)
}

// ─── wg assembly-level pins ────────────────────────────────────────────────

/// How a face's geometry is computed when building the stabilizer.
#[derive(Clone, Copy, PartialEq)]
enum Route {
    /// The post-D810-1 path: `face_point_geom`(`_3d`) + MFEM's face rule.
    Isoparametric,
    /// The pre-D810-1 chord route, reproduced verbatim: the corner chord /
    /// corner triangle for the measure, corner interpolation for the physical
    /// point, the affine vertex-Jacobian inverse for the reference point, and
    /// the pre-fix rule (`tri_rule` in *both* dimensions, only `ξ₀` used).
    Chord,
}

/// The wg face stabilizer `Σ_faces α·∫_F φᵢφⱼ dS` with `α = penalty/h`,
/// assembled independently of the wg modules.
fn wg_face_block<const D: usize>(
    mesh: &Mesh<D>,
    space: &L2Space<Mesh<D>>,
    quad_order: u8,
    penalty: f64,
    route: Route,
) -> Vec<Vec<f64>> {
    let dim = mesh.dim() as usize;
    let n = space.n_dofs();
    let mut k = vec![vec![0.0_f64; n]; n];

    for f in &InteriorFaceList::build(mesh).faces {
        face_block_add(mesh, space, &mut k, f.elem_left, f.elem_right, &f.face_nodes, quad_order, penalty, route);
    }
    let bmap = fem_assembly::dg::dg_base::build_face_elem_map(mesh, dim);
    for bf in mesh.face_iter() {
        if let Some(&el) = bmap.get(&bf) {
            let fnodes: Vec<u32> = mesh.face_nodes(bf).to_vec();
            face_block_add(mesh, space, &mut k, el, el, &fnodes, quad_order, penalty, route);
        }
    }
    k
}

#[allow(clippy::too_many_arguments)]
fn face_block_add<const D: usize>(
    mesh: &Mesh<D>,
    space: &L2Space<Mesh<D>>,
    k: &mut [Vec<f64>],
    el: u32,
    er: u32,
    fnodes: &[u32],
    quad_order: u8,
    penalty: f64,
    route: Route,
) {
    let dim = mesh.dim() as usize;
    let order = space.order() as usize;
    let ref_e: Box<dyn ReferenceElement> =
        if dim == 2 { Box::new(TriPk::new(order)) } else { Box::new(TetPk::new(order)) };
    let ne = ref_e.n_dofs();
    let (h, qf) = match route {
        Route::Isoparametric => {
            (face_measure(mesh, el, fnodes, quad_order), face_rule(dim, quad_order))
        }
        Route::Chord => (chord_measure(mesh, fnodes), tri_rule(quad_order)),
    };
    let alpha = penalty / h.max(1e-14);
    let dofs_l: Vec<usize> = space.element_dofs(el).iter().map(|&d| d as usize).collect();
    let dofs_r: Vec<usize> = space.element_dofs(er).iter().map(|&d| d as usize).collect();

    for (qi, xi) in qf.points.iter().enumerate() {
        let mut sides: Vec<(u32, &Vec<usize>)> = vec![(el, &dofs_l)];
        if el != er {
            sides.push((er, &dofs_r));
        }
        for (es, dofs) in sides {
            let (eip, w) = match route {
                Route::Isoparametric => {
                    let g = rs_face(mesh, es, fnodes, xi);
                    let mag = g.nor.iter().map(|v| v * v).sum::<f64>().sqrt();
                    (g.eip, qf.weights[qi] * mag)
                }
                Route::Chord => {
                    // Pre-fix: corner-interpolated physical point, inverted
                    // through the affine vertex Jacobian.
                    let (xp, _nor) = chord_point_normal(mesh, es, fnodes, xi);
                    (chord_invert(mesh, es, &xp), qf.weights[qi] * h)
                }
            };
            let mut pb = vec![0.0_f64; ne];
            ref_e.eval_basis(&eip, &mut pb);
            for i in 0..ne {
                for j in 0..ne {
                    let v = alpha * w * pb[i] * pb[j];
                    if v.abs() > 1e-30 {
                        k[dofs[i]][dofs[j]] += v;
                    }
                }
            }
        }
    }
}

fn face_rule(dim: usize, qo: u8) -> fem_element::reference::QuadratureRule {
    if dim == 2 { seg_rule(qo) } else { tri_rule(qo) }
}

/// `Σ_q ipw_q·|nor|_q` on the isoparametric face.
fn face_measure<const D: usize>(mesh: &Mesh<D>, elem: u32, fnodes: &[u32], qo: u8) -> f64 {
    let dim = mesh.dim() as usize;
    let qf = face_rule(dim, qo);
    let mut h = 0.0;
    for (qi, xi) in qf.points.iter().enumerate() {
        let g = rs_face(mesh, elem, fnodes, xi);
        h += qf.weights[qi] * g.nor.iter().map(|v| v * v).sum::<f64>().sqrt();
    }
    h
}

/// The pre-fix chord / corner-triangle measure.
fn chord_measure<const D: usize>(mesh: &Mesh<D>, fnodes: &[u32]) -> f64 {
    let c0 = mesh.node_coords(fnodes[0]);
    if fnodes.len() == 2 {
        let c1 = mesh.node_coords(fnodes[1]);
        ((c1[0] - c0[0]).powi(2) + (c1[1] - c0[1]).powi(2)).sqrt()
    } else {
        let c1 = mesh.node_coords(fnodes[1]);
        let c2 = mesh.node_coords(fnodes[2]);
        let u1 = [c1[0] - c0[0], c1[1] - c0[1], c1[2] - c0[2]];
        let u2 = [c2[0] - c0[0], c2[1] - c0[1], c2[2] - c0[2]];
        let n = [
            u1[1] * u2[2] - u1[2] * u2[1],
            u1[2] * u2[0] - u1[0] * u2[2],
            u1[0] * u2[1] - u1[1] * u2[0],
        ];
        (n[0] * n[0] + n[1] * n[1] + n[2] * n[2]).sqrt() / 2.0
    }
}

/// The pre-fix corner-interpolated physical point (returns its `|nor|` too).
fn chord_point_normal<const D: usize>(
    mesh: &Mesh<D>,
    _elem: u32,
    fnodes: &[u32],
    xi: &[f64],
) -> (Vec<f64>, f64) {
    let c0 = mesh.node_coords(fnodes[0]);
    if fnodes.len() == 2 {
        let c1 = mesh.node_coords(fnodes[1]);
        let n = [c1[1] - c0[1], -(c1[0] - c0[0])];
        (
            vec![c0[0] + xi[0] * (c1[0] - c0[0]), c0[1] + xi[0] * (c1[1] - c0[1])],
            (n[0] * n[0] + n[1] * n[1]).sqrt(),
        )
    } else {
        let c1 = mesh.node_coords(fnodes[1]);
        let c2 = mesh.node_coords(fnodes[2]);
        let u1 = [c1[0] - c0[0], c1[1] - c0[1], c1[2] - c0[2]];
        let u2 = [c2[0] - c0[0], c2[1] - c0[1], c2[2] - c0[2]];
        let n = [
            u1[1] * u2[2] - u1[2] * u2[1],
            u1[2] * u2[0] - u1[0] * u2[2],
            u1[0] * u2[1] - u1[1] * u2[0],
        ];
        (
            vec![
                c0[0] + xi[0] * u1[0] + xi[1] * u2[0],
                c0[1] + xi[0] * u1[1] + xi[1] * u2[1],
                c0[2] + xi[0] * u1[2] + xi[1] * u2[2],
            ],
            (n[0] * n[0] + n[1] * n[1] + n[2] * n[2]).sqrt(),
        )
    }
}

/// The pre-fix reference point: the affine vertex-Jacobian inverse applied to
/// the corner-interpolated physical point.
fn chord_invert<const D: usize>(mesh: &Mesh<D>, elem: u32, xp: &[f64]) -> Vec<f64> {
    let dim = mesh.dim() as usize;
    let nodes = mesh.element_nodes(elem);
    let x0 = mesh.node_coords(nodes[0]);
    // jac[(d, i)] = ∂x_d/∂ξ_i from the first `dim` vertices (the pre-fix
    // `local_jac`), then `ξ = J⁻¹(xp − x0)`.
    let mut a = vec![vec![0.0_f64; dim]; dim];
    for i in 0..dim {
        let xi = mesh.node_coords(nodes[1 + i]);
        for d in 0..dim {
            a[d][i] = xi[d] - x0[d];
        }
    }
    let det = if dim == 2 {
        a[0][0] * a[1][1] - a[0][1] * a[1][0]
    } else {
        a[0][0] * (a[1][1] * a[2][2] - a[1][2] * a[2][1])
            - a[0][1] * (a[1][0] * a[2][2] - a[1][2] * a[2][0])
            + a[0][2] * (a[1][0] * a[2][1] - a[1][1] * a[2][0])
    };
    let inv = if det.abs() < 1e-300 { 0.0 } else { 1.0 / det };
    let mut xi = vec![0.0_f64; dim];
    if dim == 2 {
        xi[0] = inv * (a[1][1] * (xp[0] - x0[0]) - a[0][1] * (xp[1] - x0[1]));
        xi[1] = inv * (-a[1][0] * (xp[0] - x0[0]) + a[0][0] * (xp[1] - x0[1]));
    } else {
        xi[0] = inv * ((a[1][1] * a[2][2] - a[1][2] * a[2][1]) * (xp[0] - x0[0])
            + (a[0][2] * a[2][1] - a[0][1] * a[2][2]) * (xp[1] - x0[1])
            + (a[0][1] * a[1][2] - a[0][2] * a[1][1]) * (xp[2] - x0[2]));
        xi[1] = inv * ((a[1][2] * a[2][0] - a[1][0] * a[2][2]) * (xp[0] - x0[0])
            + (a[0][0] * a[2][2] - a[0][2] * a[2][0]) * (xp[1] - x0[1])
            + (a[0][2] * a[1][0] - a[0][0] * a[1][2]) * (xp[2] - x0[2]));
        xi[2] = inv * ((a[1][0] * a[2][1] - a[1][1] * a[2][0]) * (xp[0] - x0[0])
            + (a[0][1] * a[2][0] - a[0][0] * a[2][1]) * (xp[1] - x0[1])
            + (a[0][0] * a[1][1] - a[0][1] * a[1][0]) * (xp[2] - x0[2]));
    }
    xi
}

/// The wg assembler's face block, isolated by linearity in `penalty`:
/// `K(penalty=1) − K(penalty=0)`.
fn wg_face_diff<const D: usize>(
    _mesh: &Mesh<D>,
    space: &L2Space<Mesh<D>>,
    qo: u8,
) -> Vec<Vec<f64>> {
    let k1 = assemble_wg_poisson(space, qo, 1.0);
    let k0 = assemble_wg_poisson(space, qo, 0.0);
    let n = space.n_dofs();
    let mut d = vec![vec![0.0_f64; n]; n];
    for i in 0..n {
        for p in k0.row_ptr[i]..k0.row_ptr[i + 1] {
            d[i][k0.col_idx[p] as usize] -= k0.values[p];
        }
        for p in k1.row_ptr[i]..k1.row_ptr[i + 1] {
            d[i][k1.col_idx[p] as usize] += k1.values[p];
        }
    }
    d
}

fn max_rel_diff(a: &[Vec<f64>], b: &[Vec<f64>]) -> f64 {
    let mut num = 0.0_f64;
    let mut den = 0.0_f64;
    for i in 0..a.len() {
        for j in 0..a.len() {
            num = num.max((a[i][j] - b[i][j]).abs());
            den = den.max(b[i][j].abs());
        }
    }
    num / den.max(1e-300)
}

