/// The wg **Maxwell** stabilizer uses the same face path (2-D HCurl fixture).
#[test]
fn d810_1_wg_maxwell_face_block_is_the_isoparametric_one() {
    let qo = 3;
    let mesh = curved_tri_mesh();
    let hcurl = HCurlSpace::new(mesh.clone(), 1);
    let n = hcurl.n_dofs();
    let k1 = assemble_wg_maxwell(&hcurl, qo, 1.0, &[]).0;
    let k0 = assemble_wg_maxwell(&hcurl, qo, 0.0, &[]).0;
    let mut d = vec![vec![0.0_f64; n]; n];
    for i in 0..n {
        for p in k0.row_ptr[i]..k0.row_ptr[i + 1] {
            d[i][k0.col_idx[p] as usize] -= k0.values[p];
        }
        for p in k1.row_ptr[i]..k1.row_ptr[i + 1] {
            d[i][k1.col_idx[p] as usize] += k1.values[p];
        }
    }
    let reference = wg_maxwell_face_block(&mesh, &hcurl, qo, 1.0);
    let rel = max_rel_diff(&d, &reference);
    println!("maxwell curved: wg face block vs isoparametric={rel:.3e}");
    assert!(rel < 1e-12, "wg maxwell face block != isoparametric ({rel:.3e})");
}

/// Independent assembly of the HCurl tangential-jump stabilizer through
/// `face_point_geom`.
fn wg_maxwell_face_block<const D: usize>(
    mesh: &Mesh<D>,
    hcurl: &HCurlSpace<Mesh<D>>,
    quad_order: u8,
    penalty: f64,
) -> Vec<Vec<f64>> {
    let dim = mesh.dim() as usize;
    let nd: Box<dyn VectorReferenceElement> = Box::new(TriNDk::new(1));
    let ne = nd.n_dofs();
    let n = hcurl.n_dofs();
    let mut k = vec![vec![0.0_f64; n]; n];

    let mut add = |el: u32, er: u32, fnodes: &[u32]| {
        let h = face_measure(mesh, el, fnodes, quad_order);
        let alpha = penalty / h.max(1e-14);
        let qf = face_rule(dim, quad_order);
        let dofs_l: Vec<usize> = hcurl.element_dofs(el).iter().map(|&d| d as usize).collect();
        let dofs_r: Vec<usize> = hcurl.element_dofs(er).iter().map(|&d| d as usize).collect();
        for (qi, xi) in qf.points.iter().enumerate() {
            for (es, dofs) in [(el, &dofs_l), (er, &dofs_r)] {
                let g = rs_face(mesh, es, fnodes, xi);
                let w = qf.weights[qi] * g.nor.iter().map(|v| v * v).sum::<f64>().sqrt();
                let mut pb = vec![0.0_f64; ne * dim];
                nd.eval_basis_vec(&g.eip, &mut pb);
                for i in 0..ne {
                    for j in 0..ne {
                        let v: f64 =
                            alpha * w * (0..dim).map(|d| pb[i * dim + d] * pb[j * dim + d]).sum::<f64>();
                        if v.abs() > 1e-30 {
                            k[dofs[i]][dofs[j]] += v;
                        }
                    }
                }
                if el == er {
                    break;
                }
            }
        }
    };

    for f in &InteriorFaceList::build(mesh).faces {
        add(f.elem_left, f.elem_right, &f.face_nodes);
    }
    let bmap = fem_assembly::dg::dg_base::build_face_elem_map(mesh, dim);
    for bf in mesh.face_iter() {
        if let Some(&el) = bmap.get(&bf) {
            let fnodes: Vec<u32> = mesh.face_nodes(bf).to_vec();
            add(el, el, &fnodes);
        }
    }
    k
}
