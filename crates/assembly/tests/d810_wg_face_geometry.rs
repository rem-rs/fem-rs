// ─── Fixtures (the MFEM probe's meshes, cell for cell) ─────────────────────

fn warp3(x: [f64; 3]) -> [f64; 3] {
    [
        x[0] + 0.1 * x[1] * x[2] + 0.2 * x[0] * x[0],
        x[1] + 0.05 * x[0] * x[2],
        x[2] + 0.1 * x[0] * x[1],
    ]
}

fn warp2(x: [f64; 2]) -> [f64; 2] {
    [x[0] + 0.2 * x[0] * x[0] + 0.1 * x[0] * x[1], x[1] + 0.05 * x[0] * x[1]]
}

fn warp_all<const D: usize>(mesh: &mut Mesh<D>, f: fn([f64; D]) -> [f64; D]) {
    let n_geom = mesh.geometry.as_ref().expect("curved table").coords.len() / D;
    {
        let geo = mesh.geometry.as_mut().expect("curved table");
        for k in 0..n_geom {
            let mut x = [0.0_f64; D];
            x.copy_from_slice(&geo.coords[k * D..(k + 1) * D]);
            let y = f(x);
            geo.coords[k * D..(k + 1) * D].copy_from_slice(&y);
        }
    }
    for k in 0..mesh.n_nodes() {
        let mut x = [0.0_f64; D];
        x.copy_from_slice(&mesh.coords[k * D..(k + 1) * D]);
        let y = f(x);
        mesh.coords[k * D..(k + 1) * D].copy_from_slice(&y);
    }
}

/// `Mesh::unit_cube_tet(1)` (the 6-tet Kuhn split of the unit cube) with an
/// order-2 geometry table and the probe's warp — `MakeCartesian3D(1,1,1,
/// TETRAHEDRON)` + `SetCurvature(2)` + the same warp.
fn curved_tet_mesh() -> Mesh<3> {
    let mut m = Mesh::<3>::unit_cube_tet(1);
    m.set_curvature(2);
    warp_all(&mut m, warp3);
    m
}

/// The two triangles of `MakeCartesian2D(1,1,TRIANGLE)` — the diagonal is
/// nodes 0–2 — with an order-2 geometry table and the probe's warp.
fn curved_tri_mesh() -> Mesh<2> {
    let mut m = Mesh::<2>::uniform(
        vec![0.0, 0.0, 1.0, 0.0, 1.0, 1.0, 0.0, 1.0],
        vec![0, 1, 2, 0, 2, 3],
        vec![1, 1],
        ElementType::Tri3,
        vec![0, 1, 1, 2, 2, 3, 3, 0],
        vec![1, 1, 1, 1],
        ElementType::Line2,
    );
    m.set_curvature(2);
    warp_all(&mut m, warp2);
    m
}

fn straight_tet_mesh() -> Mesh<3> {
    Mesh::<3>::unit_cube_tet(1)
}

fn straight_tri_mesh() -> Mesh<2> {
    Mesh::<2>::uniform(
        vec![0.0, 0.0, 1.0, 0.0, 1.0, 1.0, 0.0, 1.0],
        vec![0, 1, 2, 0, 2, 3],
        vec![1, 1],
        ElementType::Tri3,
        vec![0, 1, 1, 2, 2, 3, 3, 0],
        vec![1, 1, 1, 1],
        ElementType::Line2,
    )
}

