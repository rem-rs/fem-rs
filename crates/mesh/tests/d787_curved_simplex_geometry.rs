//! D787 — `fem_mesh::transformation::element_jacobian_at` on **curved
//! simplices** (`Tet4/Tet10`, `Prism6/Prism15/Prism18`) and the curved 2-D
//! families (`Tri3/Tri6`, `Quad4/Quad8/Quad9`).
//!
//! # The defect
//!
//! `element_jacobian_at` had isoparametric branches for **hexes only** (D715)
//! and **pyramids only** (D334).  Every other cell fell into the `(None, None)`
//! arm, which pairs `et.ref_elem(1)` (the P1 basis) with
//! [`raw_geometry_nodes`]-selected nodes — a table only when it is *P1-sized*.
//! A curved cell's geometry table is never P1-sized (10 nodes for a tet, 18 for
//! a prism, 9 for a quad, 6 for a triangle), so the helper silently dropped it
//! and integrated the **straight** map spanned by the element's corner nodes:
//! `Mesh::element_jacobian` (the assembly-side map) and
//! `ElementTransformation::Weight()` in MFEM both evaluate the order-`g`
//! `nodes` map instead.  Measured on the fixture below (g3-warped unit tet):
//! `element_jacobian_at` reported `∫|det J| = 2.0e-1` (the warped *corners*'
//! tetrahedron) against MFEM's `1.829847222222222e-1` — **9.3 % off** — and the
//! consumers that route through it (`DGMassInverse`, `complex::compute_l2_error`,
//! `physics::topology_optimization`, `compute_l2_error_{hcurl,hdiv,l2}` for
//! tets, `flux_recovery`'s pyramid arm) inherited the error.  See
//! `tmp/d787/README.md` for the per-consumer audit (which of the registered
//! consumers really routed through this entry point and which had their own
//! geometry path).
//!
//! # The fix (what these tests pin)
//!
//! `curved_geometry` generalises the D715 hex arm into one family-aware
//! dispatch that mirrors `Mesh::element_jacobian`'s family table:
//!
//! | cell | geometry element (order `g`) | reference frame |
//! |------|------------------------------|-----------------|
//! | `Tet4/Tet10` | `H1TetPk(g)` (closed GLL) | unit simplex |
//! | `Prism6/15/18` | `PrismPk(g)` (GLL lattice, layer-major) | `(ξ=extrusion, η, ζ)` |
//! | `Tri3/Tri6` | `H1TriPk(g)` (closed GLL) | unit triangle |
//! | `Quad4/Quad8/Quad9` | `QuadQk(g)` (closed GLL) | `[0,1]²` |
//! | `Hex*` | `HexQk(g)` (D715 arm, unchanged) | `[0,1]³` |
//!
//! gated on `geom_order >= 2` **and** a table-length match, so straight meshes
//! (including geometrically periodic ones with P1-sized tables) keep the exact
//! previous code path.  The family choice is not cosmetic: at `g = 3` the
//! equispaced `TetPk(3)`/`TriPk(3)` lattices are *not* the stored GLL one, so a
//! same-order-but-wrong-family element reads every interior node from the wrong
//! reference point (the `tet P3`/`prism P3` cases below pin that).
//!
//! # MFEM truth
//!
//! `tmp/d787/d787_probe.cpp` (MFEM 4.10 serial, `$HOME/work/d787/d787_probe`)
//! builds the same physical cell — unit cell, `SetCurvature(g)`, then the D319
//! quadratic warp `g3` applied to every geometry dof *and* every vertex, i.e.
//! exactly what `curved_unit_*` does on the fem-rs side via
//! `Mesh::set_curvature(g)` + the same warp — and dumps `Weight()`,
//! `Jacobian()`, `Transform()` at the reference points below plus
//! `Σ_q w_q |Weight()|` for an order-8 rule.  The pinned numbers were generated
//! from `tmp/d787/mfem_truth_*.txt` by `tmp/d787/gen_pins.py`
//! (`tmp/d787/pins_generated.rs`); regenerate with
//!
//! ```text
//! wsl -e bash -lc 'cd $HOME/work/d787 && ./d787_probe {tet,prism,quad,tri} 2'
//! uv run --no-project python tmp/d787/gen_pins.py
//! ```
//!
//! Reference frames: MFEM's wedge reference is the cyclic relabeling
//! `(tri-x, tri-y, extrusion)` of fem-rs' `PrismPk` frame `(extrusion, tri-x,
//! tri-y)`, so the generator rewrites every prism sample into the fem-rs frame
//! (`xi_femrs = (z, x, y)`, Jacobian columns `(c2, c0, c1)` — a 3-cycle, so
//! `det J` is frame-independent).  Tet/triangle/square reference frames are
//! identical in both codes.

