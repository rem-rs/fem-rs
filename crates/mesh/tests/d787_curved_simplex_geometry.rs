fn assert_close(got: f64, want: f64, tol: f64, what: &str) {
    let scale = want.abs().max(1.0);
    let err = (got - want).abs();
    assert!(
        err <= tol * scale,
        "{what}: got {got:.17e}, MFEM {want:.17e} (|Δ| = {err:.3e}, tol {tol:.1e} rel)"
    );
}

/// `∫|det J| dξ` over `rule` — the same `Σ_q w_q |Weight()|` MFEM's side
/// computes (assertion-safe: reports the fem-rs number before comparing).
fn volume<M: MeshTopology + ?Sized>(
    mesh: &M,
    e: u32,
    dim: usize,
    rule: &QuadratureRule,
    label: &str,
) -> f64 {
    let mut v = 0.0;
    for (xi, w) in rule.points.iter().zip(rule.weights.iter()) {
        let (jac, _xp) = element_jacobian_at(mesh, e, xi, dim);
        v += w * jac.determinant().abs();
    }
    eprintln!("{label}: ∫|det J| = {v:.17e}");
    v
}

/// One MFEM sample: `J`, `det J` and `x(ξ)` from `element_jacobian_at`.
fn check_sample<M: MeshTopology + ?Sized>(
    mesh: &M,
    dim: usize,
    e: u32,
    s: &Sample,
    label: &str,
) {
    let xi = &s.xi[..dim];
    let (jac, xp) = element_jacobian_at(mesh, e, xi, dim);
    let det = jac.determinant();
    eprintln!(
        "{label} at {xi:?}: det = {det:.17e} (MFEM {:.17e}); x = {xp:?} (MFEM {:?})",
        s.det,
        &s.xp[..dim]
    );
    assert_close(det, s.det, TOL, &format!("{label}: det J at {xi:?}"));
    for i in 0..dim {
        for j in 0..dim {
            assert_close(
                jac[(i, j)],
                s.jac[i][j],
                TOL,
                &format!("{label}: J[{i}][{j}] at {xi:?}"),
            );
        }
        assert_close(xp[i], s.xp[i], TOL, &format!("{label}: x[{i}] at {xi:?}"));
    }
}

/// The same map through both mesh-crate entries:
/// `element_jacobian_at` (dyn `MeshTopology`) vs `Mesh::element_jacobian`
/// (the assembly-side accessor, D708/D113-verified against MFEM).
fn check_agrees_with_mesh_entry<const D: usize>(
    mesh: &Mesh<D>,
    dim: usize,
    rule: &QuadratureRule,
    label: &str,
) {
    let mut worst = 0.0_f64;
    for (xi, _w) in rule.points.iter().zip(rule.weights.iter()) {
        let (j_dyn, xp_dyn) = element_jacobian_at(mesh, 0, xi, dim);
        let (j_mesh, det_mesh, xp_mesh) = mesh.element_jacobian(0, xi);
        let det_dyn = j_dyn.determinant();
        worst = worst.max((det_dyn - det_mesh).abs() / det_mesh.abs().max(1.0));
        for i in 0..dim {
            for j in 0..dim {
                worst = worst.max(
                    (j_dyn[(i, j)] - j_mesh[(i, j)]).abs() / j_mesh[(i, j)].abs().max(1.0),
                );
            }
            worst = worst.max((xp_dyn[i] - xp_mesh[i]).abs());
        }
    }
    eprintln!("{label}: dyn-vs-Mesh::element_jacobian worst |Δ| = {worst:.3e}");
    assert!(worst <= TOL, "{label}: the two mesh-crate Jacobian entries disagree ({worst:.3e})");
}

/// `geometry_jacobian` — the other public geometry entry, `(det J, J^{-T})` —
/// takes the same arms: it used to keep the P1 vertex map on every curved
/// non-pyramid cell, so its `J^{-T}` (the gradient transform
/// `physics::mixed_hyperelasticity` applies) disagreed with the map
/// `element_jacobian_at` and the assembler evaluate for the same cell.
fn check_geometry_jacobian<const D: usize>(mesh: &Mesh<D>, dim: usize, label: &str) {
    let mut worst = 0.0_f64;
    // Two reference points inside every fixture cell (tet/triangle: the
    // barycentric sum stays ≤ 1; prism: `tx + ty ≤ 1`; quad `[0,1]²`).
    let second: Vec<f64> = if dim == 3 { vec![0.1, 0.2, 0.3] } else { vec![0.1, 0.2] };
    for xi in [vec![0.25; dim], second] {
        let (j, _xp) = element_jacobian_at(mesh, 0, &xi, dim);
        let (det, jit) = fem_mesh::transformation::geometry_jacobian(mesh, 0, &xi, dim);
        worst = worst.max((det - j.determinant()).abs() / j.determinant().abs().max(1.0));
        let want = j.clone().try_inverse().expect("non-singular").transpose();
        for i in 0..dim {
            for jj in 0..dim {
                worst = worst.max((jit[(i, jj)] - want[(i, jj)]).abs());
            }
        }
    }
    eprintln!("{label}: geometry_jacobian-vs-element_jacobian_at worst |Δ| = {worst:.3e}");
    assert!(
        worst <= TOL,
        "{label}: `geometry_jacobian` disagrees with `element_jacobian_at` ({worst:.3e})"
    );
}

