// ─── straight meshes must keep the previous path bit for bit ────────────────

/// The straight path is *not* re-routed: with `geom_order == 1` (no table) the
/// P1 vertex interpolation is exactly the affine simplex map, checked here
/// against the vertex differences directly (not against the implementation's
/// own output), and against the same map through `Mesh::element_jacobian`.
#[test]
fn d787_straight_simplices_keep_the_affine_map() {
    for (label, mesh, dim) in [
        ("tet", unit_tet(), 3usize),
        ("prism", unit_prism(), 3),
    ] {
        let (jac, xp) = element_jacobian_at(&mesh, 0, &[0.25, 0.25, 0.25][..dim], dim);
        let v = mesh.element_nodes(0);
        // J[:,k] = x_{k+1} - x_0 for the affine simplex (Prism6's corner order
        // [0,1,2] = (ext,η,ζ) axes via nodes 3/1/2 — same table the reference
        // element's slot order dictates).
        let x0 = mesh.coords_of(v[0]);
        let col_of: &[usize] = if dim == 3 && v.len() == 6 { &[3, 1, 2] } else { &[1, 2, 3] };
        for (col, &n) in col_of.iter().enumerate() {
            let xn = mesh.coords_of(v[n]);
            for row in 0..dim {
                let want = xn[row] - x0[row];
                assert_close(jac[(row, col)], want, TOL, &format!("{label}: straight J[{row}][{col}]"));
            }
        }
        for row in 0..dim {
            let want = x0[row] + (0..dim).map(|k| jac[(row, k)] * 0.25).sum::<f64>();
            assert_close(xp[row], want, TOL, &format!("{label}: straight x[{row}]"));
        }
        assert_close(jac.determinant(), 1.0, TOL, &format!("{label}: straight det J"));
    }
    for (label, mesh, dim) in [("quad", unit_quad(), 2usize), ("tri", unit_tri(), 2)] {
        let (jac, _xp) = element_jacobian_at(&mesh, 0, &[0.5, 0.5][..dim], dim);
        assert_close(jac[(0, 0)], 1.0, TOL, &format!("{label}: straight J[0][0]"));
        assert_close(jac[(1, 1)], 1.0, TOL, &format!("{label}: straight J[1][1]"));
        assert_close(jac[(0, 1)], 0.0, TOL, &format!("{label}: straight J[0][1]"));
        assert_close(jac[(1, 0)], 0.0, TOL, &format!("{label}: straight J[1][0]"));
    }
}

/// A geometrically periodic-style mesh keeps a **P1-sized** geometry table
/// (`raw_geometry_nodes`'s "table only when P1-sized" rule) — the new arm must
/// not hijack it.  The table here is the vertex table itself, so the map is the
/// affine one either way.
#[test]
fn d787_p1_sized_geometry_table_keeps_the_straight_path() {
    let mut mesh = unit_tet();
    let conn = mesh.conn.clone();
    let coords = mesh.coords.clone();
    let n = mesh.n_nodes();
    mesh.geometry = Some(fem_mesh::simplex::GeometryData {
        order: 1,
        conn,
        nodes_per_elem: 4,
        coords,
        n_nodes: n,
    });
    assert_eq!(mesh.geom_order(), 1);
    let (jac, xp) = element_jacobian_at(&mesh, 0, &[0.1, 0.2, 0.3], 3);
    assert_close(jac.determinant(), 1.0, TOL, "P1-sized table: det J");
    assert_close(xp[0], 0.1, TOL, "P1-sized table: x[0]");
    assert_close(xp[1], 0.2, TOL, "P1-sized table: x[1]");
    assert_close(xp[2], 0.3, TOL, "P1-sized table: x[2]");
}
