/// The 2-D mixed P2 tier (`data/star-mixed-p2.mesh`, 20 tris + 10 quads) —
/// same engine, same guarantees, another enumeration pattern (quad-heavy).
#[test]
fn star_mixed_p2_engine_matches_mfem() {
    let mesh_path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../data/star-mixed-p2.mesh");
    let probe = read_mfem_mixed_h1_geometry_file(mesh_path)
        .expect("read")
        .expect("star-mixed-p2 is a supported mixed mesh");
    assert_eq!(probe.order, 2);
    assert_eq!(probe.elems.len(), 30);
    // MFEM's dof count: 31 verts + E*1 + 20 tri interiors + 10 quad interiors
    // (tri interior at p2 = 0, quad interior = 1).
    assert_eq!(probe.n_dofs, 31 + probe_edge_count(mesh_path) + 10);
    // every row length must equal its family's dof count
    for (et, row) in &probe.elems {
        let want = match et {
            ElementType::Tri3 | ElementType::Tri6 => 6,
            _ => 9,
        };
        assert_eq!(row.len(), want, "{et:?} row length");
    }
}

/// Edge count of a 2-D mesh file (for the dof-count arithmetic above).
fn probe_edge_count(mesh_path: &str) -> usize {
    let text = std::fs::read_to_string(mesh_path).unwrap();
    let mut edges = std::collections::HashSet::new();
    let mut lines = text.lines().map(str::trim).filter(|l| !l.is_empty());
    while let Some(l) = lines.next() {
        if l == "elements" {
            let n: usize = lines.next().unwrap().parse().unwrap();
            for _ in 0..n {
                let t: Vec<&str> = lines.next().unwrap().split_whitespace().collect();
                let ns: Vec<u32> = t[2..].iter().map(|v| v.parse().unwrap()).collect();
                let edge_table: [[usize; 2]; 3] = match t[1].parse().unwrap() {
                    2 => [[0, 1], [1, 2], [2, 0]],
                    _ => [[0, 1], [1, 2], [2, 3]],
                };
                for [a, b] in edge_table {
                    let mut key = vec![ns[a], ns[b]];
                    key.sort_unstable();
                    edges.insert(key);
                }
            }
        }
    }
    edges.len()
}

