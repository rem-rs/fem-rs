//! D117/D118: high-order H1 `nodes` geometry on **mixed** meshes.
//!
//! MFEM's `nodes` grid function numbers its dofs over the whole mesh
//! regardless of element mixture (`FiniteElementSpace::GetElementDofs`,
//! `fem/fespace.cpp`): vertices, then per-edge blocks of `p-1` dofs, then
//! per-face blocks sized by the *face* geometry (tri `(p-1)(p-2)/2`, quad
//! `(p-1)²` — MFEM's `var_face_dofs` table for mixed faces), then
//! per-element interior blocks sized by the *element* geometry.  fem-rs's
//! reader had two failure modes on such meshes (red evidence:
//! `tmp/d117/red_head.log`; before/after matrix: `tmp/d117/status.md`):
//!
//! * 2-D mixed (tri+quad): the uniform-stride generic arm attached a **silent,
//!   wrong** table — every element got `DofManager::build_pk`'s P-order
//!   *simplex* row (10 dofs at p=3), so the 22 quads of llnl-p3 were evaluated
//!   with 10 of their 16 geometry coefficients and no warning at all;
//! * 3-D mixed: loud refusal (straight-sided), for want of a per-type table.
//!
//! D117 builds the MFEM-faithful per-type table (`mixed_h1_slot_map` inside
//! fem-io) and validates it against MFEM 4.10 probes
//! (`tests/data/d117_*_cpp.txt`, generated by `tmp/d117/d117_dump.cpp` in WSL
//! `$HOME/work/d117/`, which loads each mesh with `refine=0,
//! fix_orientation=false` so `GetElementDofs` is the *file's* numbering):
//!
//! * every slot's dof id and coordinate must match MFEM bit-for-bit;
//! * the isoparametric map must reproduce `ElementTransformation::Transform`
//!   at every FE node to ≤ 1e-11;
//! * the minimum Jacobian determinant over the element nodes must equal
//!   MFEM's — for llnl-p3 that is the round's headline number
//!   `0.0029296874999967192` (MIN_DET_GLL6).
//!
//! The in-memory *storage* of a mixed table landed in **D624**: a **ragged**
//! `GeometryData` (`nodes_per_elem == 0`, per-family row lengths — MFEM's own
//! `nodes` contract), so the reader now *attaches* the verified table; the
//! never-again contract stays (a mixed table must have the right row length
//! for every element), and the end-to-end acceptance moved to
//! `d624_mixed_geometry_storage.rs`.

use fem_element::lagrange::factory::{HexQk, H1TetPk, H1TriPk, QuadQk};
use fem_element::lagrange::PrismPk;
use fem_element::ReferenceElement;
use fem_io::mfem::{read_mfem_file, read_mfem_mixed_h1_geometry_file};
use fem_mesh::element_type::ElementType;
use fem_mesh::MeshTopology;

