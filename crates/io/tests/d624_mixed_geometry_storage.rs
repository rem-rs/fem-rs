/// The reference element family each mixed-table row is evaluated with (the
/// consumer contract: `Mesh::element_jacobian`'s per-type dispatch).
fn consumer_ref_elem(et: ElementType, p: usize) -> Box<dyn ReferenceElement> {
    match et {
        ElementType::Tri3 | ElementType::Tri6 => Box::new(H1TriPk::new(p)),
        ElementType::Quad4 | ElementType::Quad8 | ElementType::Quad9 => Box::new(QuadQk::new(p)),
        ElementType::Tet4 | ElementType::Tet10 => Box::new(H1TetPk::new(p)),
        ElementType::Hex8 | ElementType::Hex20 | ElementType::Hex27 => Box::new(HexQk::new(p)),
        ElementType::Prism6 | ElementType::Prism15 | ElementType::Prism18 => {
            Box::new(PrismPk::new(p))
        }
        ElementType::Pyramid5 | ElementType::Pyramid13 => {
            // D347 consumer contract: MFEM's `SetCurvature` default (Fuentes).
            fem_element::lagrange::h1_pyramid_element(
                p,
                fem_element::lagrange::PyramidBasisType::default(),
            )
        }
        other => panic!("no consumer family for {other:?}"),
    }
}

/// MFEM reference-center of each geometry, in the *consumer* frame.
///
/// D757 (D721 follow-up): the hex consumer (`HexQk`) shares MFEM's `[0,1]³`
/// unit cube now, so the hex center is `(0.5,0.5,0.5)` verbatim — the former
/// `(0,0,0)` was the `[-1,1]³` center.
fn ref_center(et: ElementType, sdim: usize) -> Vec<f64> {
    match (et, sdim) {
        (ElementType::Tri3 | ElementType::Tri6, _) => vec![1.0 / 3.0; 2],
        (ElementType::Quad4 | ElementType::Quad8 | ElementType::Quad9, _) => vec![0.5, 0.5],
        (ElementType::Tet4 | ElementType::Tet10, _) => vec![0.25; 3],
        (ElementType::Hex8 | ElementType::Hex20 | ElementType::Hex27, _) => vec![0.5; 3],
        (ElementType::Prism6 | ElementType::Prism15 | ElementType::Prism18, _) => {
            vec![0.5, 1.0 / 3.0, 1.0 / 3.0] // PrismPk frame: (z, x, y)
        }
        (ElementType::Pyramid5 | ElementType::Pyramid13, _) => vec![0.0, 0.0, 0.25],
        _ => panic!("no center for {et:?}"),
    }
}

/// Consumer-frame reference volume (for straight elements:
/// volume = detJ(center) × this).  D757 (D721 follow-up): the hex frame is the
/// unit cube, reference volume 1, no longer `[-1,1]³`'s 8.
fn ref_volume(et: ElementType, sdim: usize) -> f64 {
    match (et, sdim) {
        (ElementType::Tri3 | ElementType::Tri6, 2) => 0.5,
        (ElementType::Quad4 | ElementType::Quad8 | ElementType::Quad9, 2) => 1.0,
        (ElementType::Tet4 | ElementType::Tet10, 3) => 1.0 / 6.0,
        (ElementType::Hex8 | ElementType::Hex20 | ElementType::Hex27, 3) => 1.0,
        (ElementType::Prism6 | ElementType::Prism15 | ElementType::Prism18, 3) => 0.5,
        (ElementType::Pyramid5 | ElementType::Pyramid13, 3) => 1.0 / 3.0,
        other => panic!("no reference volume for {other:?}"),
    }
}

/// detJ scale between the consumer frame and MFEM's `[0,1]^d` frames.
/// D757 (D721 follow-up): every consumer family — the hexahedron included —
/// now lives on MFEM's frames, so this is uniformly 1.
fn det_scale(_et: ElementType) -> f64 {
    1.0
}

/// Map an MFEM reference point into the consumer family's frame.
/// D757 (D721 follow-up): the hex is the identity now (its consumer element
/// was the last `[-1,1]³` holdout); only the prism's `(z, x, y)` axis order
/// remains.
fn to_consumer(et: ElementType, pt: &[f64], sdim: usize) -> Vec<f64> {
    match et {
        ElementType::Prism6 | ElementType::Prism15 | ElementType::Prism18 => {
            vec![pt[2], pt[0], pt[1]]
        }
        _ => pt[..sdim].to_vec(),
    }
}

// ─── probe truth (d117_dump format) ─────────────────────────────────────────

struct Probe {
    sdim: usize,
    p: usize,
    ndofs: usize,
    /// Per element: (MFEM geometry code, dof ids in MFEM slot order).
    edof: Vec<(usize, Vec<usize>)>,
    /// Per geometry: FE reference node positions (MFEM slot order).
    node_ref: Vec<(usize, Vec<[f64; 3]>)>,
    /// Per element: per-slot mapped positions.
    pt: Vec<Vec<[f64; 3]>>,
    /// Per dof: the file's stored coordinate triple.
    node_xyz: Vec<[f64; 3]>,
    mindet: f64,
    /// Per element: detJ at the reference center.
    center_det: Vec<f64>,
    /// Per element: volume (order-2p+2 rule).
    vol: Vec<f64>,
}

fn parse_probe(path: &str) -> Probe {
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("read {path}: {e}"));
    let mut pr = Probe {
        sdim: 0,
        p: 0,
        ndofs: 0,
        edof: Vec::new(),
        node_ref: Vec::new(),
        pt: Vec::new(),
        node_xyz: Vec::new(),
        mindet: f64::INFINITY,
        center_det: Vec::new(),
        vol: Vec::new(),
    };
    let mut in_noderef: Option<usize> = None;
    for line in text.lines() {
        let t: Vec<&str> = line.split_whitespace().collect();
        if t.is_empty() {
            continue;
        }
        match t[0] {
            "header" => {
                pr.sdim = t[1].parse().unwrap();
                pr.p = t[2].parse().unwrap();
                pr.ndofs = t[3].parse().unwrap();
            }
            "edof" => {
                assert_eq!(pr.edof.len(), t[1].parse::<usize>().unwrap(), "edof in element order");
                pr.edof
                    .push((t[2].parse().unwrap(), t[3..].iter().map(|v| v.parse().unwrap()).collect()));
            }
            "noderef" => {
                in_noderef = Some(t[2].parse().unwrap());
                pr.node_ref.push((t[1].parse().unwrap(), Vec::new()));
            }
            "pt" => {
                in_noderef = None;
                let e: usize = t[1].parse().unwrap();
                if pr.pt.len() <= e {
                    pr.pt.resize_with(e + 1, Vec::new);
                }
                assert_eq!(pr.pt[e].len(), t[2].parse::<usize>().unwrap(), "pt in slot order");
                pr.pt[e].push([t[3].parse().unwrap(), t[4].parse().unwrap(), t[5].parse().unwrap()]);
            }
            "mindet" => pr.mindet = t[1].parse().unwrap(),
            "node" => {
                assert_eq!(
                    pr.node_xyz.len(),
                    t[1].parse::<usize>().unwrap(),
                    "node rows in dof order"
                );
                pr.node_xyz.push([
                    t[2].parse().unwrap(),
                    t[3].parse().unwrap(),
                    t[4].parse().unwrap(),
                ]);
            }
            "center" => {
                let e: usize = t[1].parse().unwrap();
                assert_eq!(pr.center_det.len(), e, "center rows in element order");
                pr.center_det.push(t[t.len() - 1].parse().unwrap());
            }
            "vol" => {
                let e: usize = t[1].parse().unwrap();
                assert_eq!(pr.vol.len(), e, "vol rows in element order");
                pr.vol.push(t[2].parse().unwrap());
            }
            "end" => break,
            _ => {
                if let Some(n) = in_noderef {
                    let i: usize = t[0].parse().unwrap();
                    let (_, rows) = pr.node_ref.last_mut().unwrap();
                    assert_eq!(rows.len(), i, "noderef rows in slot order");
                    rows.push([t[1].parse().unwrap(), t[2].parse().unwrap(), t[3].parse().unwrap()]);
                    if rows.len() == n {
                        in_noderef = None;
                    }
                }
            }
        }
    }
    pr
}

fn geometry_code(et: &ElementType) -> u8 {
    match et {
        ElementType::Tri3 | ElementType::Tri6 => 2,
        ElementType::Quad4 | ElementType::Quad8 | ElementType::Quad9 => 3,
        ElementType::Tet4 | ElementType::Tet10 => 4,
        ElementType::Hex8 | ElementType::Hex20 | ElementType::Hex27 => 5,
        ElementType::Prism6 | ElementType::Prism15 | ElementType::Prism18 => 6,
        ElementType::Pyramid5 | ElementType::Pyramid13 => 7,
        other => panic!("no MFEM geometry code for {other:?}"),
    }
}

/// Sorted physical-node multiset of an element (for the frame-independent
/// comparison across the tet renumbering).
fn sorted_row_xyz(
    mesh: &fem_mesh::simplex::Mesh<3>,
    e: u32,
) -> Vec<([f64; 3], usize)> {
    let mut v: Vec<([f64; 3], usize)> = mesh
        .geometry_row(e)
        .iter()
        .map(|&g| {
            let c = mesh.geom_coords_of(g);
            ([c[0], c[1], c[2]], g as usize)
        })
        .collect();
    v.sort_by(|a, b| a.0.partial_cmp(&b.0).unwrap());
    v
}

