//! D624: mixed-mesh high-order H1 geometry **storage** — the ragged
//! `GeometryData` (`nodes_per_elem == 0`, per-family row lengths).
//!
//! The D117 round delivered the MFEM-verified mixed slot map
//! (`mixed_h1_slot_map` + the `read_mfem_mixed_h1_geometry_file` probe) but
//! the reader could not *store* a mixed table: `GeometryData` had a single
//! uniform stride.  D624 lands the storage and flips `build_h1_geometry`'s
//! mixed gate from "precise warning + straight-sided" to **attach**.
//!
//! Acceptance (MFEM 4.10 probe truth, `tmp/d117/d117_dump.cpp` runs in WSL
//! `$HOME/work/{d117,d624}/`; 2-D and tet+hex+prism fixtures from D117, the
//! hex+prism+pyramid fixture generated by MFEM itself via
//! `SetCurvature(2)` + `Save`):
//!
//! * `llnl-p3` (2-D tri+quad P3): the attached table's min detJ over the FE
//!   nodes equals MFEM's `0.0029296874999965726`, and the reader's
//!   "wrong orientation 15/26" report drops to zero (the CW-in-straight
//!   quads are positively oriented in their curved geometry);
//! * `fichera-mixed-p2` (tet+hex+prism P2): the geometry survives the
//!   reader's `mark_tet_mesh_for_refinement` rotation — per-element physical
//!   node sets match the file-frame probe bit-for-bit, min detJ
//!   `0.35384952876017473` is kept;
//! * `fichera-mixed-16-p2` (hex+prism+pyramid P2, **new** fixture generated
//!   by MFEM's own `SetCurvature`): reads curved (was loud-refused before
//!   D624) — the Fuentes-pyramid rows pin the pyramid numbering end-to-end,
//!   volumes match the probe per element;
//! * uniform meshes and AMR: a refinement of the curved llnl-p3 keeps the
//!   mixed geometry (children interpolate the parent map).

