#[test]
fn gll_01_matches_mfem_bit_for_bit() {
    for &(np, i, x, w) in MFEM_GLL_01 {
        let (xs, ws) = gauss_lobatto_01_arbitrary(np);
        assert_eq!(
            xs[i], x.parse::<f64>().unwrap(),
            "np={np} i={i}: node must reproduce MFEM's %.17g value bit-for-bit"
        );
        assert_eq!(
            ws[i], w.parse::<f64>().unwrap(),
            "np={np} i={i}: weight must reproduce MFEM's %.17g value bit-for-bit"
        );
    }
}

/// The `[-1,1]` rule is the exact affine image of the `[0,1]` rule MFEM
/// stores: `x = 2·z − 1`, `w = 2·w₀₁` (doubling is exact in binary floats),
/// with `x₀ = −1`, `x_{np−1} = +1` and the MFEM symmetry `x_i = −x_{np−1−i}`.
#[test]
fn gll_minus_plus_one_is_exact_affine_image() {
    for np in 6..=12usize {
        let (x01, w01) = gauss_lobatto_01_arbitrary(np);
        let (xs, ws) = gauss_lobatto_arbitrary(np);
        for i in 0..np {
            assert_eq!(xs[i], 2.0 * x01[i] - 1.0, "np={np} i={i}: node mapping");
            assert_eq!(ws[i], 2.0 * w01[i], "np={np} i={i}: weight scaling");
        }
        assert_eq!(xs[0], -1.0);
        assert_eq!(xs[np - 1], 1.0);
        // MFEM's own symmetry lives on the [0,1] side (`symm = 1 − z`);
        // point antisymmetry of the mapped [-1,1] values is exact-math
        // true but not bit-true after the two roundings of `2·z − 1`.
        for i in 1..=(np - 1) / 2 {
            assert_eq!(
                x01[np - 1 - i],
                1.0 - x01[i],
                "np={np} i={i}: MFEM symmetry"
            );
            assert_eq!(ws[i], ws[np - 1 - i], "np={np} i={i}: weight symmetry");
        }
    }
}
