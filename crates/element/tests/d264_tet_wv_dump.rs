fn check_rule(order: u8, mfem: &str) {
    let r = tet_rule(order);
    let mut pts: Vec<[f64; 4]> = r
        .points
        .iter()
        .zip(r.weights.iter())
        .map(|(p, &w)| [p[0], p[1], p[2], w])
        .collect();
    pts.sort_by(|a, b| {
        a[..3]
            .partial_cmp(&b[..3])
            .unwrap()
            .then(a[3].partial_cmp(&b[3]).unwrap())
    });
    let mfem_pts: Vec<Vec<f64>> = mfem
        .lines()
        .filter(|l| l.trim().starts_with('+'))
        .map(|l| l.split_whitespace().map(|t| t.parse::<f64>().unwrap()).collect())
        .collect();
    assert_eq!(pts.len(), mfem_pts.len(), "order={order}: point count vs MFEM");
    for (i, (a, b)) in pts.iter().zip(mfem_pts.iter()).enumerate() {
        for d in 0..4 {
            assert_eq!(
                a[d], b[d],
                "order={order}, sorted point {i}, component {d}: rust {} vs mfem {}",
                a[d], b[d]
            );
        }
    }
}

#[test]
fn tet_rules_8_10_bit_match_mfem() {
    check_rule(8, MFEM_ORDER_8);
    check_rule(9, MFEM_ORDER_9);
    check_rule(10, MFEM_ORDER_10);
}

#[test]
fn tet_rules_8_10_all_positive_weights() {
    for order in [8u8, 9, 10] {
        let r = tet_rule(order);
        let wsum: f64 = r.weights.iter().sum();
        assert!((wsum - 1.0 / 6.0).abs() < 1e-12, "order={order}: sum={wsum}");
        for (i, &w) in r.weights.iter().enumerate() {
            assert!(w > 0.0, "order={order}, weight[{i}]={w} is not positive");
        }
    }
}
