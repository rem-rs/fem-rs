/// The generic k=2 element must agree with the explicit `TriND2` dual basis
/// (same functionals ⟹ same basis).
#[test]
fn tri_ndk2_agrees_with_tri_nd2() {
    let a = TriNDk::new(2);
    let b = TriND2;
    for xi in &[[0.137, 0.421], [0.25, 0.3], [1.0 / 3.0, 1.0 / 3.0]] {
        let mut va = vec![0.0; 16];
        let mut vb = vec![0.0; 16];
        a.eval_basis_vec(xi, &mut va);
        b.eval_basis_vec(xi, &mut vb);
        for (x, y) in va.iter().zip(vb.iter()) {
            assert!((x - y).abs() < 1e-12, "TriNDk(2) vs TriND2 at {xi:?}: {x} vs {y}");
        }
    }
    let mut ca = vec![0.0; 8];
    let mut cb = vec![0.0; 8];
    a.eval_curl(&[0.137, 0.421], &mut ca);
    b.eval_curl(&[0.137, 0.421], &mut cb);
    for (x, y) in ca.iter().zip(cb.iter()) {
        assert!((x - y).abs() < 1e-12, "TriNDk(2) curl: {x} vs {y}");
    }
}

