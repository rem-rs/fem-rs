//! D38 regression: `TriNDk`/`TetNDk` against MFEM 4.10 `ND_TriangleElement` /
//! `ND_TetrahedronElement` reference dumps.
//!
//! The expected values below were emitted by a C++ 4.10 harness
//! (`$HOME/work/d38_gentest.cpp`, WSL) linking `libmfem.a`:
//!
//! ```text
//! ND_TriangleElement(3).GetNodes() / CalcVShape / CalcCurlShape at (0.137, 0.421)
//! ND_TetrahedronElement(3) .GetNodes() / CalcVShape / CalcCurlShape at (0.111, 0.253, 0.198)
//! ND_TetrahedronElement(4) .GetNodes() / CalcVShape / CalcCurlShape at (0.111, 0.253, 0.198)
//! ```
//!
//! This pins both halves of the D38 nodal redesign: the DOF **points**
//! (`FE::Nodes`, which the space's `dof_coords`/pairing rely on) and the
//! resulting **basis functions** (the dual basis of the point-value
//! functionals `σ_i(Φ) = Φ(x_i)·t̂_i`).

#![allow(clippy::needless_range_loop)] // index arithmetic mirrors the C++ dump layout

use fem_element::nedelec::{TetNDk, TriND2, TriNDk};
use fem_element::reference::VectorReferenceElement;

/// Worst absolute deviation over the entries compared by `check_nodes`.
fn check_nodes(got: &[Vec<f64>], want: &[f64], dim: usize, tag: &str) -> f64 {
    assert_eq!(got.len() * dim, want.len(), "{tag}: node count");
    let mut worst = 0.0_f64;
    for (i, p) in got.iter().enumerate() {
        for d in 0..dim {
            worst = worst.max((p[d] - want[i * dim + d]).abs());
        }
    }
    worst
}

/// Worst absolute deviation of `eval_basis_vec` + `eval_curl` against a dump
/// array laid out as `[phi_0(dim), curl_0(curl_dim), phi_1(dim), ...]`.
fn check_shape(
    elem: &dyn VectorReferenceElement,
    xi: &[f64],
    want: &[f64],
    dim: usize,
    curl_dim: usize,
    tag: &str,
) -> f64 {
    let n = elem.n_dofs();
    assert_eq!(n * (dim + curl_dim), want.len(), "{tag}: dump size");
    let mut phi = vec![0.0_f64; n * dim];
    let mut curl = vec![0.0_f64; n * curl_dim];
    elem.eval_basis_vec(xi, &mut phi);
    elem.eval_curl(xi, &mut curl);
    let mut worst = 0.0_f64;
    for i in 0..n {
        for d in 0..dim {
            worst = worst.max((phi[i * dim + d] - want[i * (dim + curl_dim) + d]).abs());
        }
        for d in 0..curl_dim {
            let dev = curl[i * curl_dim + d] - want[i * (dim + curl_dim) + dim + d];
            worst = worst.max(dev.abs());
        }
    }
    worst
}

#[test]
fn tri_nd3_matches_mfem_dump() {
    let e = TriNDk::new(3);
    let wn = check_nodes(&e.dof_coords(), &TRI3_NODES, 2, "TriND3 nodes");
    let ws = check_shape(&e, &[0.137, 0.421], &TRI3_VS_CURL, 2, 1, "TriND3 shape");
    assert!(wn <= 1e-14, "TriND3 node deviation {wn:.3e}");
    assert!(ws <= 1e-12, "TriND3 shape/curl deviation {ws:.3e}");
    eprintln!("TriND3: nodes {wn:.3e}, shape+curl {ws:.3e}");
}

