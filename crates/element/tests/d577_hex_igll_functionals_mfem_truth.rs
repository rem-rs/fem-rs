/// The probe's polynomial vector fields (probe `field_h*` / `field_q*`).
fn field_h(f: usize, x: [f64; 3]) -> [f64; 3] {
    match f {
        0 => [1.0, 0.0, 0.0],
        1 => [0.5, -1.0, 2.0],
        2 => [x[0] * x[0], x[1] * (x[0] + 0.5), x[2] * x[2] * x[2]],
        _ => [x[0] * x[1] * x[2], x[1] * x[1] - 0.25, x[0] - x[2]],
    }
}

fn field_q(f: usize, _x: [f64; 2]) -> [f64; 2] {
    match f {
        0 => [1.0, 0.0],
        1 => [0.5, -1.0],
        _ => unreachable!(),
    }
}

/// `[0,1]` GLL closed points (`p+2` of them) per order.
fn cp01(k: usize) -> &'static [f64] {
    match k {
        0 => &[0.0, 1.0],
        1 => &[0.0, 0.5, 1.0],
        2 => &[0.0, 0.276393202250021, 0.723606797749979, 1.0],
        3 => &[
            0.0,
            0.17267316464601146,
            0.5,
            0.8273268353539885,
            1.0,
        ],
        _ => unreachable!(),
    }
}

fn idx01(cp: &[f64], t: f64) -> usize {
    cp.iter()
        .position(|&c| (c - t).abs() < 1e-12)
        .unwrap_or_else(|| panic!("coord {t} not in {cp:?}"))
}

/// Gauss points bracketing the sample span per rule size (`k <= 3` keeps the
/// per-axis rule at 2 or 3 `[0,1]` Gauss-Legendre points).
fn gl_bracket(npts: usize) -> (f64, f64) {
    match npts {
        1 => (0.5, 0.5),
        2 => (0.21132486540518710671, 0.78867513459481286553),
        3 => (0.11270166537925831174, 0.88729833462074170214),
        _ => unreachable!("npts {npts}"),
    }
}

/// Recover the functional's `(c, ic, s1, s2, flip)` from its samples —
/// independent of the implementation's enumeration internals.
fn recover(f: &fem_element::raviart_thomas::hex_rtk::IntegratedDofFunctional3D,
           k: usize)
           -> (usize, usize, usize, usize, usize) {
    let c = f.t.iter().position(|&v| v != 0.0).unwrap();
    let flip = usize::from(f.t[c] < 0.0);
    let (a1, a2) = free_axes(c);
    let cp = cp01(k);
    let npts = {
        let n = (f.samples.len() as f64).sqrt().round() as usize;
        assert_eq!(n * n, f.samples.len(), "sample grid not square");
        n
    };
    let (u0, u1) = gl_bracket(npts);
    let axis = |a: usize| {
        let mut mn = f64::INFINITY;
        let mut mx = f64::NEG_INFINITY;
        for (pt, _) in &f.samples {
            mn = mn.min(pt[a]);
            mx = mx.max(pt[a]);
        }
        let h = (mx - mn) / (u1 - u0);
        idx01(cp, (mn - h * u0 + 1.0) / 2.0)
    };
    let ic = idx01(cp, (f.samples[0].0[c] + 1.0) / 2.0);
    (c, ic, axis(a1), axis(a2), flip)
}

/// The per-DOF functional data (component, closed index, sub-cell indices,
/// flip) matches MFEM's slot walk for k = 1..3 (384 DOFs, zero mismatches in
/// the probe diff).
#[test]
fn hex_igll_functional_layout_matches_mfem() {
    for k in 1..=3usize {
        let packed: &[u16] = match k {
            1 => &HEX_LAYOUT_K1,
            2 => &HEX_LAYOUT_K2,
            _ => &HEX_LAYOUT_K3,
        };
        let funs = HexRTk::new(k).integrated_functionals();
        assert_eq!(funs.len(), packed.len(), "k={k}: dof count");
        for (n, fun) in funs.iter().enumerate() {
            let (c, ic, s1, s2, flip) = recover(fun, k);
            let want = packed[n];
            let got =
                (c as u16) | ((ic as u16) << 2) | ((s1 as u16) << 5)
                    | ((s2 as u16) << 7) | ((flip as u16) << 9);
            assert_eq!(got, want, "k={k} dof {n}");
        }
    }
}

/// Applying the fem-rs functionals to the probe's polynomial fields over the
/// unit cube reproduces MFEM `ProjectIntegrated` (the public `Project`
/// dispatch) DOF for DOF at machine precision.
#[test]
fn hex_igll_functional_values_match_mfem_project() {
    for &(k, f) in HEX_SEL.iter() {
        let el = HexRTk::new(k);
        let funs = el.integrated_functionals();
        let truth = hex_truth(k, f);
        assert_eq!(funs.len(), truth.len(), "k={k} field={f}: dof count");
        for (n, fun) in funs.iter().enumerate() {
            // unit-cube physical map: x = (xi+1)/2 per axis,
            // J_xi = J_t·diag(1/2) => adj(J_xi) = adj(J_t)/4 (adj(J_t) = I).
            let mut val = 0.0_f64;
            for (pt, w) in &fun.samples {
                let xp = [
                    (pt[0] + 1.0) / 2.0,
                    (pt[1] + 1.0) / 2.0,
                    (pt[2] + 1.0) / 2.0,
                ];
                let fv = field_h(f, xp);
                val += w
                    * (fv[0] * fun.t[0] + fv[1] * fun.t[1] + fv[2] * fun.t[2])
                    / 4.0;
            }
            assert!(
                (val - truth[n]).abs() <= 5e-13 * (1.0 + truth[n].abs()),
                "k={k} field={f} dof {n}: {val} vs mfem {}",
                truth[n]
            );
        }
    }
}

/// The functionals are dual to the element's own IGLL basis up to the
/// standing D227-era frame debt: the fem-rs IntegratedGLL open modes carry
/// the `V_mfem/16` normalization (two `×¼` open factors, `hex_rtk::partial_open`),
/// so each open factor integrates to `1/2` over its GLL sub-cell of the
/// `[-1,1]` frame and the dual matrix is `(1/4)·I` — uniform over face and
/// interior DOFs, exactly δ/4.  (The quad IGLL twin, which lives on `[0,1]`
/// without the pull-back, is δ-exact: see `d368_quad_nd_rt_igll_mfem_parity`.)
#[test]
fn hex_igll_functionals_are_dual_up_to_frame() {
    for k in 0..=3usize {
        let el = HexRTk::new(k);
        let funs = el.integrated_functionals();
        let n = el.n_dofs();
        assert_eq!(funs.len(), n, "k={k}: functional count");
        let mut phi = vec![0.0_f64; n * 3];
        for (i, fi) in funs.iter().enumerate() {
            let mut sigma = vec![0.0_f64; n];
            for (pt, w) in &fi.samples {
                el.eval_basis_vec(pt, &mut phi);
                for (j, s) in sigma.iter_mut().enumerate() {
                    *s += w
                        * (phi[j * 3] * fi.t[0]
                            + phi[j * 3 + 1] * fi.t[1]
                            + phi[j * 3 + 2] * fi.t[2]);
                }
            }
            for (j, &s) in sigma.iter().enumerate() {
                let want = if i == j { 0.25 } else { 0.0 };
                assert!(
                    (s - want).abs() < 1e-12,
                    "k={k}: sigma_{i}(phi_{j}) = {s} (want {want})"
                );
            }
        }
    }
}

/// Control: the quad IGLL twin's table (`QuadRTk::integrated_functionals`,
