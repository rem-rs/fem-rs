/// square — MFEM's `[0,1]` SEGMENT rules make its sub-cell samples identical
/// to the fem-rs ones, J = I, no frame factors (D368 pinned shapes/duals;
/// this pins the projected DOF values themselves).
#[test]
fn quad_igll_functional_values_match_mfem_project() {
    for &(k, f) in QUAD_SEL.iter() {
        let el = QuadRTk::new_integrated_gll(k);
        let funs = el.integrated_functionals();
        let truth = quad_truth(k, f);
        assert_eq!(funs.len(), truth.len(), "k={k} field={f}: dof count");
        for (n, fun) in funs.iter().enumerate() {
            let mut val = 0.0_f64;
            for (pt, w) in &fun.samples {
                let fv = field_q(f, *pt);
                val += w * (fv[0] * fun.t[0] + fv[1] * fun.t[1]);
            }
            assert!(
                (val - truth[n]).abs() <= 5e-13 * (1.0 + truth[n].abs()),
                "k={k} field={f} dof {n}: {val} vs mfem {}",
                truth[n]
            );
        }
    }
}
