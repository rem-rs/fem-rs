#[test]
fn d103_p1tet_nonconf_structural() {
    let e = P1TetNonConf;
    let mut v = vec![0.0; 4];
    let mut g = vec![0.0; 12];
    for p in &[
        vec![0.1, 0.2, 0.3],
        vec![0.25, 0.25, 0.25],
        vec![0.0, 0.5, 0.25],
        vec![1.0 / 3.0, 1.0 / 3.0, 1.0 / 3.0],
    ] {
        e.eval_basis(p, &mut v);
        let s: f64 = v.iter().sum();
        assert!((s - 1.0).abs() < 1e-15, "POU at {p:?}: sum={s}");
        e.eval_grad_basis(p, &mut g);
        for j in 0..3 {
            let sg: f64 = (0..4).map(|i| g[i * 3 + j]).sum();
            assert_eq!(sg, 0.0, "grad sum at {p:?} dir {j}");
        }
    }
}

#[test]
fn d103_refined_bilinear2d_partition_of_unity_and_delta() {
    let e = RefinedBiLinear2D;
    // POU on every branch (values agree across the internal seam).
    let mut v = vec![0.0; 9];
    for p in &[
        vec![0.25, 0.25],
        vec![0.75, 0.25],
        vec![0.75, 0.75],
        vec![0.25, 0.75],
        vec![0.5, 0.5],
        vec![0.5 + 1e-13, 0.5],
        vec![0.5, 0.5 + 1e-13],
        vec![0.3, 0.6],
    ] {
        e.eval_basis(p, &mut v);
        let s: f64 = v.iter().sum();
        assert!((s - 1.0).abs() < 1e-15, "POU at {p:?}: sum={s}");
    }
    // Nodal delta property: phi_i(node_j) = delta_ij exactly (all dyadic).
    let nodes = e.dof_coords();
    for (j, node) in nodes.iter().enumerate() {
        e.eval_basis(node, &mut v);
        for (i, x) in v.iter().enumerate() {
            let expect = if i == j { 1.0 } else { 0.0 };
            assert_eq!(*x, expect, "phi_{i} at node_{j} = {x}");
        }
    }
}

#[test]
fn d103_refined_trilinear3d_partition_of_unity_and_quirk() {
    let e = RefinedTriLinear3D;
    let mut v = vec![0.0; 27];
    // The 8-corner trilinear template sums to 1 for ANY (Lx,Ly,Lz), so the
    // partition of unity holds on every branch — including the crossed-Lx
    // ones (all-dyadic points, exact fp).
    for p in &[
        vec![0.25, 0.25, 0.25],
        vec![0.75, 0.25, 0.25],
        vec![0.25, 0.75, 0.25],
        vec![0.75, 0.75, 0.25],
        vec![0.25, 0.25, 0.75],
        vec![0.75, 0.25, 0.75],
        vec![0.25, 0.75, 0.75],
        vec![0.75, 0.75, 0.75],
        vec![0.5, 0.5, 0.5],
    ] {
        e.eval_basis(p, &mut v);
        let s: f64 = v.iter().sum();
        assert_eq!(s, 1.0, "POU at {p:?}: sum={s}");
    }
    // What the crossed-Lx quirk (T2/T3/T6/T7 branches) *does* break is the
    // nodal delta property.  Probe truth at node 3 = (0,1,0) (T2 branch,
    // Lx = 2-2x = 2): phi_2 = -1, phi_10 = 2, everything else 0 — pinned
    // verbatim, not "fixed" (PT RBH 0 1 0 ... in d103_truth.txt).
    let n3: Vec<f64> = e.dof_coords()[3].clone();
    assert_eq!(n3, vec![0.0, 1.0, 0.0]);
    e.eval_basis(&n3, &mut v);
    for (i, x) in v.iter().enumerate() {
        let expect = match i {
            2 => -1.0,
            10 => 2.0,
            _ => 0.0,
        };
        assert_eq!(*x, expect, "phi_{i} at node 3 = {x} (mfem quirk)");
    }
}
