//! D103 — the three remaining element arms (D911/D912/D913), pinned against
//! MFEM 4.10 ground truth (bit-exact).
//!
//! Truth source: the C++ probe `tmp/d103elc/d103_probe.cpp`, built against
//! `$HOME/mfem410_ser` (MFEM 4.10 serial) with
//! `g++ -std=c++17 -O2 -I$HOME/mfem410_ser d103_probe.cpp
//! $HOME/mfem410_ser/libmfem.a`, output archived as
//! `tmp/d103elc/d103_truth.txt` (349 lines, 296 PT points).  The probe dumps,
//! for MFEM's `LinearNonConf3DFECollection` TET arm and
//! `RefinedLinearFECollection` SQUARE/CUBE arms:
//! - `GetFE(geom, 1)` dof/order per geometry (`COLL` lines),
//! - element `GetDim/GetOrder/GetDof/GetGeomType` (`FE` lines),
//! - the `Nodes` table (`NODE` lines),
//! - `CalcShape` + row-major `CalcDShape` on fixed dyadic point sets (`PT`
//!   lines) covering every piecewise sub-element branch interior *and*
//!   straddle points on both sides of every branch boundary (±1/64 and
//!   ±1e-13; the RefinedBiLinear/TriLinear selectors are closed
//!   `x <= 0.5`-style first-match chains).
//!
//! A standalone harness (`tmp/d103elc/compare.rs`, same point sets) compared
//! this port against the dump: worst |Δ| = 0.0 and worst relative Δ = 0.0
//! over **all** shape/dshape/node entries — bit-exact, including every
//! boundary-band point.  The pins below are transcribed mechanically from
//! `d103_truth.txt` (generator `tmp/d103elc/gen_pins.py`; every float literal
//! round-trips to the identical f64).
//!
//! Upstream quirks faithfully preserved (do not "fix" them here):
//! - RefinedBiLinear2D T0 branch: `dshape(7,0)` is assigned twice in MFEM
//!   (`fe_fixed_order.cpp:3788-3789`); the second write wins and
//!   `dshape(7,1)` stays 0 → gradient row 7 = `(2(Lx−1), 0)`.
//! - RefinedTriLinear3D branches T2/T3/T6/T7 use the "crossed" `Lx`
//!   assignment (`Lx = 2−2x` where `x <= 1/2`, `Lx = 1−2x` where `x >= 1/2`),
//!   so there the basis is not nodal at its corner nodes (e.g.
//!   `phi_10(node 3) = 2`, `phi_2(node 3) = −1`); the partition of unity
//!   itself still sums to 1 because the 8-corner template does for any
//!   `(Lx,Ly,Lz)` (pinned below).

use fem_element::nonconforming::P1TetNonConf;
use fem_element::refined_linear::{RefinedBiLinear2D, RefinedTriLinear3D};
use fem_element::ReferenceElement;

/// One probe point: reference coords, MFEM CalcShape, MFEM row-major
/// CalcDShape (`dshape[i*dim + j]`).
struct Pin {
    xi: &'static [&'static f64],
    shape: &'static [f64],
    dshape: &'static [f64],
}

fn check_pins(elem: &dyn ReferenceElement, pins: &[Pin]) {
    let dim = elem.dim() as usize;
    let nd = elem.n_dofs();
    for (k, p) in pins.iter().enumerate() {
        let xi: Vec<f64> = p.xi.iter().map(|s| **s).collect();
        assert_eq!(xi.len(), dim, "pin {k}: coord count");
        assert_eq!(p.shape.len(), nd, "pin {k}: shape len");
        assert_eq!(p.dshape.len(), nd * dim, "pin {k}: dshape len");
        let mut shape = vec![0.0; nd];
        let mut grads = vec![0.0; nd * dim];
        elem.eval_basis(&xi, &mut shape);
        elem.eval_grad_basis(&xi, &mut grads);
        for (i, (&a, &b)) in shape.iter().zip(p.shape.iter()).enumerate() {
            assert_eq!(a, b, "pin {k} xi={xi:?}: shape[{i}] rust={a} mfem={b}");
        }
        for (i, (&a, &b)) in grads.iter().zip(p.dshape.iter()).enumerate() {
            assert_eq!(a, b, "pin {k} xi={xi:?}: dshape[{i}] rust={a} mfem={b}");
        }
    }
}

fn check_nodes(elem: &dyn ReferenceElement, nodes: &[&[f64]]) {
    let dc = elem.dof_coords();
    assert_eq!(dc.len(), elem.n_dofs(), "dof_coords count");
    assert_eq!(dc.len(), nodes.len(), "nodes table count");
    for (i, n) in nodes.iter().enumerate() {
        assert_eq!(dc[i], n.to_vec(), "node {i} coords");
    }
}

// ── MFEM facts (probe `FE`/`COLL` lines) ────────────────────────────────────
// COLL LinearNonConf3D geom=4 (TET) dof=4 order=1  ← P1TetNonConf (D911)
// COLL RefinedLinear  geom=3 (SQUARE) dof=9 order=1  ← RefinedBiLinear2D (D912)
// COLL RefinedLinear  geom=5 (CUBE)   dof=27 order=2 ← RefinedTriLinear3D (D913)
// FE P1T dim=3 order=1 ndof=4 ; FE RBQ dim=2 order=1 ndof=9 ;
// FE RBH dim=3 order=2 ndof=27

#[test]
fn d103_collection_dof_anchors() {
    // The three arms this round closes, as seen through
    // FiniteElementCollection::FiniteElement(geom, 1) in the probe dump.
    assert_eq!((P1TetNonConf.n_dofs(), P1TetNonConf.order()), (4, 1));
    assert_eq!((RefinedBiLinear2D.n_dofs(), RefinedBiLinear2D.order()), (9, 1));
    assert_eq!(
        (RefinedTriLinear3D.n_dofs(), RefinedTriLinear3D.order()),
        (27, 2)
    );
}

