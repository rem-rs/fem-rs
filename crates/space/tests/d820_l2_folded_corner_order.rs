fn nums(text: &str) -> Vec<Vec<f64>> {
    text.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| {
            l.split_whitespace()
                .map(|t| t.parse::<f64>().expect("number"))
                .collect()
        })
        .collect()
}

/// Worst |diff| between `L2Space`'s per-element dof coordinates and the MFEM
/// dump rows (`row = [e, x0, y0, …]`, element index carried in `row[0]` — the
/// rows may cover a subset of the elements), slot k of element e vs row e.
fn worst_diff<const D: usize>(
    space: &L2Space<fem_mesh::Mesh<D>>,
    rows: &[Vec<f64>],
) -> (f64, usize, usize) {
    let dpe = space.element_dofs(0).len();
    let mut worst = 0.0_f64;
    let mut worst_e = 0;
    let mut worst_k = 0;
    for row in rows {
        let e = row[0] as usize;
        for (k, chunk) in row[1..].chunks_exact(D).enumerate() {
            let dof = e * dpe + k;
            for (d, &want) in chunk.iter().enumerate() {
                let got = space.dof_coords()[dof * D + d];
                let diff = (got - want).abs();
                if diff > worst {
                    worst = diff;
                    worst_e = e;
                    worst_k = k;
                }
            }
        }
    }
    (worst, worst_e, worst_k)
}

/// The primary D817-2 pin: on the order-2 folded square, every one of the 81
/// `L2Space` dof coordinates must equal MFEM's own nodes-gf value — including
/// the wrap elements whose geometry only exists in the per-element table.
#[test]
fn sq_p2_folded_dof_coords_match_mfem() {
    let mesh = load_mesh_2d("data/periodic-square-p2.mesh");
    let space = L2Space::new_with_basis(mesh, 2, L2Basis::GaussLobatto);
    assert_eq!(space.n_dofs(), 81);
    let (worst, e, k) = worst_diff(&space, &nums(MFEM_SQ_P2));
    assert!(
        worst <= TOL,
        "element {e} dof {k}: worst |diff| = {worst:.3e} — the L2 P2 folded \
         table's dof coordinates (tensor-lex corner order) diverge from MFEM"
    );
}

/// The literal D817-2 statement: on the P2 folded table the element corners
/// sit at the **tensor-lex** dof slots `[0, 2, 8, 6]` = `i + j·(p+1)`, not the
/// SQUARE vertex ring `[0, 1, 2, 3]`.  Element 0 of the fixture spans
/// `[0, 2/3]²`: MFEM's dump has dof 2 at ref (1,0) → phys (2/3, 0) and dof 6
/// at ref (0,1) → phys (0, 2/3) — under a ring interpretation slot 2 would be
/// the (2/3, 2/3) corner and slot 6 the (0, 2/3) edge point.
#[test]
fn sq_p2_corners_are_tensor_lex_not_ring() {
    let mesh = load_mesh_2d("data/periodic-square-p2.mesh");
    let space = L2Space::new_with_basis(mesh, 2, L2Basis::GaussLobatto);
    let p = 2usize;
    // ring corner (cx, cy) with refs in {0,1} → GLL node (cx·p, cy·p) →
    // lex slot i + j·(p+1).
    let lex_of_corner = |i: usize, j: usize| i * p + j * p * (p + 1);
    for e in 0..space.mesh().n_elements() {
        let e = e as usize;
        let gnodes = space.mesh().geometry_nodes(e as u32);
        assert_eq!(gnodes.len(), 9, "L2_T1_2D_P2 folded table: 9 dofs/element");
        let corner = |ring: usize| space.mesh().geom_coords_of(gnodes[ring]);
        // SQUARE ring order: (0,0), (1,0), (1,1), (0,1).
        let ring_refs = [(0usize, 0usize), (1, 0), (1, 1), (0, 1)];
        for (ring, (i, j)) in ring_refs.iter().enumerate() {
            let slot = e * 9 + lex_of_corner(*i, *j);
            let c = corner(ring);
            for d in 0..2 {
                let got = space.dof_coords()[slot * 2 + d];
                assert!(
                    (got - c[d]).abs() <= TOL,
                    "element {e} ring corner {ring} (ref ({i},{j})): dof slot \
                     {slot} coord {d} = {got} != geometry corner {} — the \
                     corner slots are not tensor-lex",
                    c[d]
                );
            }
        }
        // And the smoking gun from the dump: slot 2 (lex (1,0)) is the low-y
        // corner (ref (1,0)), not the (1,1) corner a ring order would put there.
        let (slot2_y, slot6_y) = (
            space.dof_coords()[(e * 9 + 2) * 2 + 1],
            space.dof_coords()[(e * 9 + 6) * 2 + 1],
        );
        assert!(
            slot2_y < slot6_y,
            "element {e}: lex slot 2 y = {slot2_y} must sit below slot 6 y = \
             {slot6_y} (tensor-lex corners)"
        );
    }
}

/// The geometry must come from the per-element folded table, not the shared
/// (mean) vertex table: the fixture's vertex coordinates top out at y = 4/3
/// (the y = 2 ≡ y = 0 seam's mean is 1.0), while the wrap elements' dof
/// coordinates reach the true y = 2.
#[test]
fn sq_p2_folded_geometry_beats_vertex_table() {
    let mesh = load_mesh_2d("data/periodic-square-p2.mesh");
    let space = L2Space::new_with_basis(mesh, 2, L2Basis::GaussLobatto);
    let max_vertex_y = (0..space.mesh().n_nodes() as u32)
        .map(|v| space.mesh().node_coords(v)[1])
        .fold(f64::NEG_INFINITY, f64::max);
    let max_dof_y = space
        .dof_coords()
        .iter()
        .skip(1)
        .step_by(2)
        .copied()
        .fold(f64::NEG_INFINITY, f64::max);
    assert!(
        (max_vertex_y - 4.0 / 3.0).abs() <= 1e-12,
        "shared vertex table max y = {max_vertex_y}, expected the 4/3 mean table"
    );
    assert!(
        (max_dof_y - 2.0).abs() <= TOL,
        "dof coordinates max y = {max_dof_y}, expected the true folded geometry y = 2"
    );
}

