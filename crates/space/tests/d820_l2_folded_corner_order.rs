//! D820 — L² order ≥ 2 folded (periodic) `nodes` tables: the **tensor-lex
//! corner order** of the dof coordinate extraction (D817-2, open since
//! round 81's D816-4 noted the corpus had no order ≥ 2 folded file).
//!
//! MFEM ground truth (probe `tmp/d83c/probe.cpp` → `$HOME/work/d83c/probe`,
//! stdout archived `tmp/d83c/probe_run1.out`): fixtures are built through
//! MFEM's own `Mesh::MakePeriodic` path — `SetCurvature(p, true)` (discont ⇒
//! `L2_FECollection(p, dim, BasisType::GaussLobatto)`, mesh.cpp:7211) *then*
//! `MakePeriodic` (mesh.cpp:6205) on a 3×3 (2-D) / 3×3×3 (3-D) Cartesian mesh
//! of side 2, torus period 2 — and written with `Save(path, 16)`:
//!
//! * `data/periodic-square-p2.mesh` — `L2_T1_2D_P2`, 9 elements / 81 dofs
//! * `data/periodic-square-p3.mesh` — `L2_T1_2D_P3`, 9 elements / 144 dofs
//! * `data/periodic-cube-p2.mesh`   — `L2_T1_3D_P2`, 27 elements / 729 dofs
//!
//! The `L2_QuadrilateralElement` / `L2_HexahedronElement` Nodes fill loops
//! (`fe_l2.cpp:96` / `fe_l2.cpp:313`) enumerate `(i, j[, k])` **lexicographically
//! with i fastest** at the closed GLL points `OpenPoints(p, GaussLobatto)`, and
//! both carry `L2_DOF_MAP`, whose array is left **empty = identity** (pinned by
//! the probe: `GetDofMap().Size() == 0` for all three tables).  So a folded
//! order ≥ 2 table stores its element corners at the tensor-lex dof slots
//!
//! ```text
//! quad p: corner ref (i, j)   → lex slot i + j·(p+1)          (p2: [0,2,8,6])
//! hex  p: corner ref (i, j, k) → i + j·(p+1) + k·(p+1)²      (p2: [0,2,8,6,18,20,26,24])
//! ```
//!
//! i.e. **not** the SQUARE/CUBE vertex-ring dof order of the P1 folded tables.
//! The read side already permutes the file's lex order onto the mesh reference
//! element's own slot order (`crates/io/src/mfem.rs`,
//! `l2_geometry_slots`/`mfem_l2_slots`), so `L2Space`'s corner extraction
//! (`geometry_nodes(e)` first 4/8 entries, ring order) stays correct — these
//! tests pin that end-to-end against MFEM's own per-element dof values (dump
//! format `tmp/d81a/*_l2_elems_r0.txt`).

