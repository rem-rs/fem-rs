/// 3-D: the `L2_T1_3D_P2` folded cube (the table whose absence D816-4
/// registered).  MFEM's own values are reproduced two ways: three raw dump
/// rows (including the far wrap cell `[4/3, 2]³`), and — because every
/// element of this axis-aligned lattice is the affine image of its min corner
/// with per-axis step 1/3 (verified against the full dump:
/// `awk` over all 27 rows × 27 dofs, 0 mismatches at 1e-12) — the analytic
/// anchor `dof0[e] + (i, j, k)/3` for the whole 729-dof table.
#[test]
fn cube_p2_folded_dof_coords_match_mfem() {
    let mesh = load_mesh_3d("data/periodic-cube-p2.mesh");
    let space = L2Space::new_with_basis(mesh, 2, L2Basis::GaussLobatto);
    assert_eq!(space.n_dofs(), 729);

    // Raw rows first.
    let (worst, e, k) = worst_diff(&space, &nums(MFEM_CUBE_P2_ROWS));
    assert!(
        worst <= TOL,
        "raw row: element {e} dof {k}: worst |diff| = {worst:.3e} vs MFEM"
    );

    // Full table via the analytic anchor (step 1/3 = half the 2/3 cell edge).
    let dof0 = nums(MFEM_CUBE_P2_DOF0);
    assert_eq!(dof0.len(), 27);
    let step = 1.0_f64 / 3.0;
    for (e, origin) in dof0.iter().enumerate() {
        for k in 0..27usize {
            let (i, j, kf) = ((k % 3) as f64, ((k / 3) % 3) as f64, (k / 9) as f64);
            let want = [
                origin[0] + i * step,
                origin[1] + j * step,
                origin[2] + kf * step,
            ];
            let dof = e * 27 + k;
            for d in 0..3 {
                let got = space.dof_coords()[dof * 3 + d];
                assert!(
                    (got - want[d]).abs() <= TOL,
                    "element {e} dof {k} coord {d}: {got} != {w} (MFEM dof0 \
                     anchor + tensor-lex step)",
                    w = want[d]
                );
            }
        }
    }
}
