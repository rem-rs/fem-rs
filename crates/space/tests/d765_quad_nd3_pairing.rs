/// Every order 3/4 DOF of the paired element must be the MFEM
/// `ND_QuadrilateralElement(p)` DOF: same `FE::Nodes` site and same functional
/// tangent (`dof2tk`, with the `dof_map` sign already baked into the basis).
/// Before D765 this failed for `p >= 3`: the assembler paired the legacy
/// `QuadNDk` (open nodes at `i/p`, top/left edge slots ascending in `+x`/`+y`).
#[test]
fn paired_quad_element_ge3_is_the_mfem_nd_quadrilateral() {
    for p in [2usize, 3, 4] {
        let paired = paired_vector_reference_element(SpaceType::HCurl, fem_mesh::element_type::ElementType::Quad4, 2, p as u8);
        let el = QuadND::new(p);
        assert_eq!(paired.n_dofs(), 2 * p * (p + 1), "p={p}: ND quad DOF count");
        assert_eq!(paired.n_dofs(), el.n_dofs());
        let (mfem_nodes, mfem_tangs) = match p {
            2 => (&MFEM_NODES_P2[..], &MFEM_TANGS_P2[..]),
            3 => (&MFEM_NODES_P3[..], &MFEM_TANGS_P3[..]),
            _ => (&MFEM_NODES_P4[..], &MFEM_TANGS_P4[..]),
        };
        let coords = paired.dof_coords();
        assert_eq!(coords.len(), mfem_nodes.len());
        for i in 0..coords.len() {
            assert!(
                (coords[i][0] - mfem_nodes[i][0]).abs() < 1e-15
                    && (coords[i][1] - mfem_nodes[i][1]).abs() < 1e-15,
                "p={p}: paired element node {i} = {:?} != MFEM FE::Nodes {:?}",
                coords[i],
                mfem_nodes[i]
            );
        }
        let tangs = el.dof_tangents();
        for i in 0..tangs.len() {
            assert!(
                (tangs[i][0] - mfem_tangs[i][0]).abs() < 1e-15
                    && (tangs[i][1] - mfem_tangs[i][1]).abs() < 1e-15,
                "p={p}: QuadND tangent {i} = {:?} != MFEM dof2tk {:?}",
                tangs[i],
                mfem_tangs[i]
            );
        }
        // The space's own tables must have exactly this many local slots.
        let space = HCurlSpace::new(inline_quad(), p as u8);
        assert_eq!(
            space.element_dofs(0).len(),
            paired.n_dofs(),
            "p={p}: space slot count vs paired element DOF count (the D765 drift guard)"
        );
    }
}

/// `HCurlSpace`'s quad ND3 slot/sign tables are MFEM's `ND_FECollection(3, 2)`
/// `GetElementDofs` tables (entity-major global numbering; local edge slot `m`
/// of a reversed local edge carries global slot `k-1-m` with sign `-1`).
#[test]
fn space_quad3_tables_match_mfem_nd_fecollection() {
    let space = HCurlSpace::new(inline_quad(), 3);
    assert_eq!(space.n_dofs(), MFEM_QUAD3_N_DOFS);
    for (e, (gold_dofs, gold_signs)) in [
        (&MFEM_ELEM0_DOFS[..], &MFEM_ELEM0_SIGNS[..]),
        (&MFEM_ELEM1_DOFS[..], &MFEM_ELEM1_SIGNS[..]),
    ]
    .into_iter()
    .enumerate()
    {
        let dofs = space.element_dofs(e as u32);
        let signs = space.element_signs(e as u32);
        assert_eq!(dofs.len(), gold_dofs.len(), "elem {e} slot count");
        for i in 0..dofs.len() {
            assert_eq!(
                dofs[i] as i32, gold_dofs[i],
                "elem {e} local slot {i}: global dof {} != MFEM {}",
                dofs[i], gold_dofs[i]
            );
            assert!(
                (signs[i] - gold_signs[i]).abs() < 1e-15,
                "elem {e} local slot {i}: sign {} != MFEM {}",
                signs[i],
                gold_signs[i]
            );
        }
    }
}

/// `HCurlSpace::interpolate_vector` at order 3 must reproduce MFEM's
/// `Project_ND`/`GridFunction::ProjectCoefficient` global DOF values for
/// `f = (sin(pi x) cos(pi y), x^2 - y)` — all 312 of them (edges: the
/// canonical `(min -> max)` point-value functionals; interiors: the missing
/// branch this test pins, D765).
#[test]
fn interpolate_vector_matches_mfem_project_nd_quad3() {
    let space = HCurlSpace::new(inline_quad(), 3);
    let uh = space.interpolate_vector(&|x| fcoef(x));
    let u = uh.as_slice();
    assert_eq!(u.len(), MFEM_PROJ_P3_QUAD.len());
    let mut max_err = 0.0_f64;
    for i in 0..u.len() {
        let want = MFEM_PROJ_P3_QUAD[i];
        let err = (u[i] - want).abs() / (1.0 + want.abs());
        max_err = max_err.max(err);
        assert!(
            (u[i] - want).abs() < 1e-12 * (1.0 + want.abs()),
            "dof {i}: interpolate_vector {:.17e} != MFEM Project_ND {:.17e}",
            u[i],
            want
        );
    }
    assert!(max_err < 1e-12, "max relative deviation {max_err}");
}

/// Focused form of the previous test (the D765 red tooth): the 12 interior DOFs
/// of element 0 were *exactly zero* before the fix — `interpolate_vector` had no
/// branch for 2-D quad `k >= 3` and fell through the tri / 3-D arms.
#[test]
fn quad3_interior_dofs_are_projected_not_zero() {
    let space = HCurlSpace::new(inline_quad(), 3);
    let uh = space.interpolate_vector(&|x| fcoef(x));
    let u = uh.as_slice();
    let base = MFEM_ELEM0_FIRST_INTERIOR;
    for m in 0..12 {
        let i = base + m;
        let want = MFEM_PROJ_P3_QUAD[i];
        assert!(
            (u[i] - want).abs() < 1e-12 * (1.0 + want.abs()),
            "element 0 interior dof {m} (global {i}): {:.17e} != MFEM {:.17e}",
            u[i],
            want
        );
    }
    // The first interior block of element 0 is O(1e-2): an all-zero row is a
    // silent-zero defect, not a small value.
    let max = (0..12).map(|m| u[base + m].abs()).fold(0.0, f64::max);
    assert!(max > 1e-2, "element 0 interior DOFs are (near) zero: max |u| = {max}");
}
