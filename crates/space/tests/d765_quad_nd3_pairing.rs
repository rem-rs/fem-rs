/// MFEM `GridFunction::ProjectCoefficient(vc)` for the probe's
/// `f = (sin(pi x) cos(pi y), x^2 - y)`.
fn fcoef(x: &[f64]) -> Vec<f64> {
    use std::f64::consts::PI;
    vec![(PI * x[0]).sin() * (PI * x[1]).cos(), x[0] * x[0] - x[1]]
}

