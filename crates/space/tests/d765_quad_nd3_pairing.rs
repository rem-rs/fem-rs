//! D765 — 2-D quad NDk (k >= 3): the space/assembler/evaluator pairing verdict.
//!
//! **Adjudicated defect.** `HCurlSpace`'s quad slot/sign tables are the MFEM
//! `ND_FECollection(p, 2)` tables: local edge slot `m` of local edge
//! `(li, lj)` is the DOF functional `sigma(Phi) = Phi(x_m) . t_m` at the m-th
//! **Gauss-Legendre** point along the local edge direction, and the top/left
//! edges (whose local direction is reversed w.r.t. the canonical `(min, max)`
//! direction) carry slot order `k-1-m` with sign `-1` — exactly MFEM's
//! `dof_map` / `dof2tk` / `DofOrderForOrientation` tables.  From order 3 on the
//! assembly dispatcher (`vector_assembler::vec_ref_elem_choice` and its
//! `postproc` mirror) handed the space the legacy homemade `QuadNDk` instead
//! (equispaced open nodes, top/left edge slots enumerated ascending in `+x`/`+y`
//! against their traversal direction), which is *not* that element: the
//! assembled matrix was not the bilinear form of the space at all
//! (`ex22 -p 1 -o 3 -m data/inline-quad.mesh`: `||Re|| = 6.603119e-2` vs the
//! C++ `9.42458e-3`, 7.0x).  The fix points every consumer at the MFEM-faithful
//! `fem_element::nedelec::QuadND`
//! (`ND_QuadrilateralElement(p, GaussLobatto, GaussLegendre)`).
//!
//! Golden data: probes `tmp/d765/d765_slots.cpp` / `tmp/d765/d765_project.cpp`
//! (built against MFEM 4.10 `$HOME/mfem410_ser`; binaries + full outputs in
//! `$HOME/work/d765/`, raw numbers and the slot-by-slot table in
//! `tmp/d765/slot_adjudication.md`):
//! * `d765_slots <p> <mesh>` — `ND_QuadrilateralElement(p)` `FE::Nodes`, the
//!   functional tangent inferred from `CalcVShape` at each node, the raw
//!   `dof_map`, and `ND_FECollection(p, 2)`'s per-element DOF tables (with
//!   MFEM's signed `-1-id` orientation encoding) on `data/inline-quad.mesh`;
//! * `d765_project <p> <mesh>` — `GridFunction::ProjectCoefficient` of
//!   `f = (sin(pi x) cos(pi y), x^2 - y)`, i.e. MFEM's `Project_ND` global DOF
//!   values in MFEM's own (entity-major, D158-layout) numbering, which is the
//!   oracle for `HCurlSpace::interpolate_vector`.

