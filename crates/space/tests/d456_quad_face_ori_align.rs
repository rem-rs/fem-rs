fn load(rel: &str) -> Mesh<3> {
    let path = format!("{}/../../{}", env!("CARGO_MANIFEST_DIR"), rel);
    let mfem = read_mfem_file(&path).unwrap_or_else(|e| panic!("failed to read {path}: {e}"));
    mfem.mesh3d.unwrap_or_else(|| panic!("{rel} must be a 3-D mesh"))
}

fn assert_signed(actual: &[f64], want: &[i8], ctx: String) {
    assert_eq!(actual.len(), want.len(), "{ctx}: sign count");
    for (i, (&a, &w)) in actual.iter().zip(want.iter()).enumerate() {
        assert_eq!(a, w as f64, "{ctx}: sign[{i}]");
    }
}

/// Slot-level table check: fem-rs `transform_grid` (+ `rt_face_sign`) must
/// reproduce every MFEM QuadDofOrd row entry for entry, p = 1 and 2,
/// Or = 0..=7.  RED before the D456 fix: fem-rs rows r2/r6 are transposed
/// against MFEM (fem-rs r2 == MFEM r6 and vice versa).
#[test]
fn quad_doford_matches_mfem_table() {
    let tables: Vec<(usize, Vec<&[i32]>)> = vec![(
            1,
            MFEM_QUAD_P1.iter().map(|r| r.as_slice()).collect(),
        ), (
            2,
            MFEM_QUAD_P2.iter().map(|r| r.as_slice()).collect(),
        )];
    for (p, table) in &tables {
        let side = p + 1;
        for (or, row) in table.iter().enumerate() {
            let sign = rt_face_sign(or);
            for j in 0..side {
                for i in 0..side {
                    let o = i + j * side;
                    let (ic, jc) = transform_grid(i, j, side, or);
                    let idx = jc * side + ic;
                    let (want_idx, want_sgn) = if row[o] >= 0 {
                        (row[o] as usize, 1.0)
                    } else {
                        ((-1 - row[o]) as usize, -1.0)
                    };
                    assert_eq!(
                        (idx, sign),
                        (want_idx, want_sgn),
                        "QuadDofOrd p={p} Or={or} slot (i={i}, j={j})"
                    );
                }
            }
        }
    }
}

/// Same check for the triangular-face grid (`TriDofOrd`) — green before and
/// after D456 (the tri side was already verbatim MFEM).
#[test]
fn tri_doford_matches_mfem_table() {
    let tables: Vec<(usize, Vec<&[i32]>)> = vec![(
            1,
            MFEM_TRI_P1.iter().map(|r| r.as_slice()).collect(),
        ), (
            2,
            MFEM_TRI_P2.iter().map(|r| r.as_slice()).collect(),
        )];
    for (p0, table) in &tables {
        let p = *p0;
        for (or, row) in table.iter().enumerate() {
            let sign = rt_face_sign(or);
            let mut used = vec![false; row.len()];
            for j in 0..=p {
                for i in 0..=(p - j) {
                    let o = j * (2 * p + 3 - j) / 2 + i;
                    let idx = tri_face_grid_transform(p, or, j, i);
                    let (want_idx, want_sgn) = if row[o] >= 0 {
                        (row[o] as usize, 1.0)
                    } else {
                        ((-1 - row[o]) as usize, -1.0)
                    };
                    assert_eq!(
                        (idx, sign),
                        (want_idx, want_sgn),
                        "TriDofOrd p={p} Or={or} slot (i={i}, j={j})"
                    );
                    used[idx as usize] = true;
                }
            }
            assert!(
                used.iter().all(|&u| u),
                "TriDofOrd p={p} Or={or} must permute all {} slots",
                row.len()
            );
        }
    }
}

