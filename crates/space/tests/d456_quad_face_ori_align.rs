//! D456 — `transform_grid` (quad faces) must match MFEM
//! `RT_FECollection::QuadDofOrd` verbatim, and the tri-face analogue
//! `tri_face_grid_transform` must match `TriDofOrd`
//! (MFEM 4.10 `fem/fe_coll.cpp`, `InitFaces`: QuadDofOrd loop at
//! fe_coll.cpp:2712-2730, TriDofOrd loop at fe_coll.cpp:2695-2710; the rows
//! are served by `DofOrderForOrientation(SQUARE/TRIANGLE, Or)`).
//!
//! Ground truth was dumped from MFEM 4.10 serial by
//! `tmp/d456/probe_d456.cpp`:
//! 1. the raw `DofOrderForOrientation` tables (p = 1, 2, Or = 0..7/0..5,
//!    signs=true default: odd rows carry the `-1-x` encoding), pinned below
//!    as `MFEM_QUAD_P*` / `MFEM_TRI_P*`;
//! 2. `GetElementVDofs` for 2-element meshes whose shared face realizes
//!    every orientation reachable between two positively-oriented elements:
//!    hex pair Or∈{1,3,5,7} (k = 1, 2), tet pair Or∈{1,3,5}, prism pair on a
//!    quad face Or∈{3,7}, stacked prism pair on a tri face Or∈{1,3,5}
//!    (the `tmp/d398/d398_probe.cpp` multi-orientation pattern).
//!
//! Reachability theorem (verified by exhaustive search over all
//! positive-Jacobian numberings of the neighbour element, probe output
//! `tmp/d456/out/probe_d456.out`): two valid elements share each interior
//! face from opposite sides, so conforming interior faces ALWAYS carry odd
//! orientations; Or = 0 occurs for canonical (first-registered) faces and
//! the even nonzero rows (quad 2/4/6, tri 2/4) are table-level only.  The
//! D456 lesion — fem-rs `transform_grid` rows r2/r6 transposed against
//! MFEM's QuadDofOrd — is therefore pinned by the table test below, while
//! the mesh-integration pins hold both before and after the fix (they guard
//! the reachable rows 1/3/5/7, 0 and the tri side against regressions).

